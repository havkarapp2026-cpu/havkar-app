    function language() {
        let stored = "";

        try {
            stored = localStorage.getItem("havkar_language")
                || localStorage.getItem("selectedLanguage")
                || localStorage.getItem("language")
                || "en";
        } catch (error) {
            stored = "en";
        }

        return String(stored).replace(/"/g, "").trim().toLowerCase() || "en";
    }

    function apply() {
        const code = language();
        const pack = packs[code] || null;

        document.documentElement.lang = pack ? code : "en";
        document.documentElement.dir = RTL[code] ? "rtl" : "ltr";

        if (!pack) {
            return;
        }

        const walker = document.createTreeWalker(
            document.body,
            NodeFilter.SHOW_TEXT
        );
        const nodes = [];

        while (walker.nextNode()) {
            nodes.push(walker.currentNode);
        }

        nodes.forEach(function (node) {
            const parent = node.parentElement;

            if (!parent || parent.tagName === "SCRIPT" || parent.tagName === "STYLE") {
                return;
            }

            const clean = String(node.nodeValue || "").replace(/\s+/g, " ").trim();

            if (!Object.prototype.hasOwnProperty.call(pack, clean)) {
                return;
            }

            const current = node.nodeValue || "";
            const leading = current.match(/^\s*/)[0];
            const trailing = current.match(/\s*$/)[0];
            node.nodeValue = leading + pack[clean] + trailing;
        });

        if (typeof document.querySelectorAll === "function") {
            document.querySelectorAll("[aria-label]").forEach(function (element) {
                const label = element.getAttribute("aria-label");

                if (Object.prototype.hasOwnProperty.call(pack, label)) {
                    element.setAttribute("aria-label", pack[label]);
                }
            });
        }
    }

    if (document.readyState === "loading") {
        document.addEventListener("DOMContentLoaded", apply, { once: true });
    } else {
        apply();
    }
