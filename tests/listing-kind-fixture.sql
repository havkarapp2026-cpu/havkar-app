CREATE POLICY "Allow public read ads"
ON public.ads
FOR SELECT
TO anon, authenticated
USING (
  status IS NULL
  OR btrim(status) = ''
  OR lower(btrim(status)) = 'active'
  OR (SELECT auth.uid()) = user_id
);

CREATE POLICY "Enable read access for all users"
ON public.ads
FOR SELECT
TO public
USING (
  status IS NULL
  OR btrim(status) = ''
  OR lower(btrim(status)) = 'active'
  OR (SELECT auth.uid()) = user_id
);

CREATE POLICY "Enable insert for authenticated users only"
ON public.ads
FOR INSERT
TO authenticated
WITH CHECK (
  (SELECT auth.uid()) = user_id
  AND status = 'active'
);

CREATE POLICY "Owners can update their own ads"
ON public.ads
FOR UPDATE
TO authenticated
USING ((SELECT auth.uid()) = user_id)
WITH CHECK ((SELECT auth.uid()) = user_id);

CREATE POLICY "Owners can delete their own ads when nothing depends on them"
ON public.ads
FOR DELETE
TO authenticated
USING (
  (SELECT auth.uid()) = user_id
  AND NOT public.ad_has_blocking_dependencies(id)
);

CREATE POLICY "Anyone can read ad saves"
ON public.ad_saves
FOR SELECT
TO authenticated
USING (true);

CREATE POLICY "Users can create their own ad saves"
ON public.ad_saves
FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can delete their own ad saves"
ON public.ad_saves
FOR DELETE
TO authenticated
USING (auth.uid() = user_id);

CREATE POLICY "Users can view their conversations"
ON public.conversations
FOR SELECT
TO authenticated
USING (auth.uid() = buyer_id OR auth.uid() = seller_id);

