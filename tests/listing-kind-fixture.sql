CREATE OR REPLACE FUNCTION public.enforce_ad_listing_status()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  normalized text;
BEGIN
  IF TG_OP = 'INSERT' THEN
    normalized := pg_catalog.lower(
      pg_catalog.btrim(COALESCE(NEW.status, ''))
    );

    IF normalized = '' OR normalized = 'active' THEN
      NEW.status := 'active';
      RETURN NEW;
    END IF;

    RAISE EXCEPTION 'new advertisements must use status active'
      USING ERRCODE = '23514';
  END IF;

  IF TG_OP = 'UPDATE'
     AND NEW.status IS DISTINCT FROM OLD.status THEN
    RAISE EXCEPTION 'advertisement status cannot be changed'
      USING ERRCODE = '42501';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER enforce_ad_listing_status
BEFORE INSERT OR UPDATE ON public.ads
FOR EACH ROW
EXECUTE FUNCTION public.enforce_ad_listing_status();

CREATE OR REPLACE FUNCTION public.enforce_ad_owner_write()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF current_user = 'anon' THEN
    RAISE EXCEPTION 'anonymous users cannot create or change ads'
      USING ERRCODE = '42501';
  END IF;

  IF current_user = 'authenticated' THEN
    IF TG_OP = 'INSERT' THEN
      IF NEW.user_id IS DISTINCT FROM auth.uid() THEN
        RAISE EXCEPTION 'ads can only be created for the current user'
          USING ERRCODE = '42501';
      END IF;
    ELSIF TG_OP = 'UPDATE' THEN
      IF OLD.user_id IS DISTINCT FROM auth.uid()
         OR NEW.user_id IS DISTINCT FROM OLD.user_id THEN
        RAISE EXCEPTION 'users cannot change ad ownership'
          USING ERRCODE = '42501';
      END IF;
    ELSIF TG_OP = 'DELETE' THEN
      IF OLD.user_id IS DISTINCT FROM auth.uid() THEN
        RAISE EXCEPTION 'users cannot delete another user ad'
          USING ERRCODE = '42501';
      END IF;
      RETURN OLD;
    END IF;
  END IF;

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER enforce_ad_owner_write
BEFORE INSERT OR DELETE OR UPDATE ON public.ads
FOR EACH ROW
EXECUTE FUNCTION public.enforce_ad_owner_write();

CREATE OR REPLACE FUNCTION public.ad_has_blocking_dependencies(target_ad_id bigint)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM public.ads
    WHERE id = target_ad_id
      AND user_id = auth.uid()
  ) THEN
    RETURN true;
  END IF;

  RETURN EXISTS (
    SELECT 1 FROM public.ad_saves WHERE ad_id = target_ad_id
  )
  OR EXISTS (
    SELECT 1 FROM public.ad_comments WHERE ad_id = target_ad_id
  )
  OR EXISTS (
    SELECT 1 FROM public.ad_reactions WHERE ad_id = target_ad_id
  )
  OR EXISTS (
    SELECT 1 FROM public.conversations WHERE ad_id = target_ad_id
  );
END;
$$;

GRANT EXECUTE ON FUNCTION public.ad_has_blocking_dependencies(bigint)
  TO authenticated;

ALTER TABLE public.ads ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ad_saves ENABLE ROW LEVEL SECURITY;
