ON public.service_bookings FOR INSERT TO authenticated
WITH CHECK (
  customer_id = (SELECT auth.uid())
  AND provider_id <> (SELECT auth.uid())
  AND status = 'pending'
  AND EXISTS (
    SELECT 1 FROM public.services s
    WHERE s.id = service_bookings.service_id
      AND s.provider_id = service_bookings.provider_id
      AND s.status = 'active'
  )
);

CREATE POLICY "Providers can update received bookings"
ON public.service_bookings FOR UPDATE TO authenticated
USING (provider_id = (SELECT auth.uid()) AND status = ANY (ARRAY['pending','accepted']))
WITH CHECK (provider_id = (SELECT auth.uid()) AND status = ANY (ARRAY['accepted','declined','completed']));

CREATE POLICY "Customers can cancel own bookings"
ON public.service_bookings FOR UPDATE TO authenticated
USING (customer_id = (SELECT auth.uid()) AND status = ANY (ARRAY['pending','accepted']))
WITH CHECK (customer_id = (SELECT auth.uid()) AND status = 'cancelled');

CREATE POLICY "Users can view related bookings"
ON public.service_bookings FOR SELECT TO authenticated
USING (customer_id = auth.uid() OR provider_id = auth.uid());

CREATE POLICY "Users can view their own notifications"
ON public.notifications FOR SELECT TO authenticated
USING (auth.uid() = user_id);

CREATE POLICY "Users can update their own notifications"
ON public.notifications FOR UPDATE TO authenticated
USING (auth.uid() = user_id)
