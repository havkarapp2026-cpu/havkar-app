CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;

CREATE SCHEMA IF NOT EXISTS auth;

CREATE TABLE IF NOT EXISTS auth.users (
  id uuid PRIMARY KEY,
  email_confirmed_at timestamptz
);

ALTER TABLE auth.users
  ADD COLUMN IF NOT EXISTS raw_app_meta_data jsonb NOT NULL DEFAULT '{}'::jsonb;

CREATE TABLE IF NOT EXISTS auth.sessions (
  id uuid PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE
);

CREATE OR REPLACE FUNCTION auth.uid()
RETURNS uuid
LANGUAGE sql
STABLE
AS $$
  SELECT NULLIF(current_setting('havkar.test_uid', true), '')::uuid;
$$;

CREATE OR REPLACE FUNCTION auth.jwt()
RETURNS jsonb
LANGUAGE sql
STABLE
AS $$
  SELECT NULLIF(current_setting('havkar.test_jwt', true), '')::jsonb;
$$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    CREATE ROLE anon NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    CREATE ROLE authenticated NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
    CREATE ROLE service_role NOLOGIN NOBYPASSRLS;
  END IF;
END $$;

CREATE SCHEMA IF NOT EXISTS havkar_private;

GRANT USAGE ON SCHEMA auth, public, havkar_private TO anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION auth.uid() TO anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION auth.jwt() TO anon, authenticated, service_role;

CREATE TABLE IF NOT EXISTS public.services (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  provider_id uuid NOT NULL REFERENCES auth.users (id),
  title text NOT NULL,
  category text NOT NULL,
  description text NOT NULL,
  price numeric,
  currency text NOT NULL DEFAULT 'EUR',
  price_type text NOT NULL DEFAULT 'fixed',
  location text,
  image_url text,
  status text NOT NULL DEFAULT 'active'
);

CREATE TABLE IF NOT EXISTS public.service_bookings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  service_id bigint NOT NULL REFERENCES public.services (id),
  customer_id uuid NOT NULL REFERENCES auth.users (id),
  provider_id uuid NOT NULL REFERENCES auth.users (id),
  booking_date date,
  booking_time time,
  message text,
  status text NOT NULL DEFAULT 'pending',
  CONSTRAINT service_booking_not_self CHECK (customer_id <> provider_id),
  CONSTRAINT service_booking_status_check CHECK (
    status IN ('pending', 'accepted', 'declined', 'cancelled', 'completed')
  )
);

ALTER TABLE public.services ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.services FORCE ROW LEVEL SECURITY;
ALTER TABLE public.service_bookings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.service_bookings FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS services_read_for_booking ON public.services;
CREATE POLICY services_read_for_booking
  ON public.services
  FOR SELECT TO authenticated
  USING (status = 'active' OR provider_id = (SELECT auth.uid()));

DROP POLICY IF EXISTS service_bookings_insert_customer ON public.service_bookings;
CREATE POLICY service_bookings_insert_customer
  ON public.service_bookings
  FOR INSERT TO authenticated
  WITH CHECK (customer_id = (SELECT auth.uid()));

DROP POLICY IF EXISTS service_bookings_update_party ON public.service_bookings;
CREATE POLICY service_bookings_update_party
  ON public.service_bookings
  FOR UPDATE TO authenticated
  USING (
    customer_id = (SELECT auth.uid())
    OR provider_id = (SELECT auth.uid())
  )
  WITH CHECK (
    customer_id = (SELECT auth.uid())
    OR provider_id = (SELECT auth.uid())
  );

DROP POLICY IF EXISTS service_bookings_select_party ON public.service_bookings;
CREATE POLICY service_bookings_select_party
  ON public.service_bookings
  FOR SELECT TO authenticated
  USING (
    customer_id = (SELECT auth.uid())
    OR provider_id = (SELECT auth.uid())
  );

GRANT SELECT ON public.services TO authenticated;
GRANT SELECT, INSERT, UPDATE ON public.service_bookings TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;
