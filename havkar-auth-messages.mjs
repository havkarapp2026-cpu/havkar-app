export function authLanguages() {
    return Object.keys(DIRECTIONS);
}

export function authDirection(language) {
    return DIRECTIONS[language] || "ltr";
}

export function authMessage(english, language) {
    if (!english || language === "en" || !DIRECTIONS[language]) {
        return english;
    }
    const row = MESSAGES[english];
    return row && row[language] ? row[language] : english;
}

export function authFailureMessage(error, fallback) {
    const code = String(
        (error && (error.code || error.error_code || error.name)) || ""
    ).toLowerCase();
    const text = String((error && error.message) || "").toLowerCase();
    if (code === "over_email_send_rate_limit" || text.includes("rate limit")) {
        return "Too many messages were sent. Please wait and try again.";
    }
    if (code === "email_not_confirmed" || text.includes("email not confirmed")) {
        return "Your email address is not confirmed. Please confirm your email before logging in.";
    }
    if (code === "weak_password" || text.includes("password should be") || text.includes("weak password")) {
        return "The password is too weak. Use at least 8 characters.";
    }
    if (
        code === "user_already_exists" ||
        code === "email_exists" ||
        text.includes("already registered") ||
        text.includes("already been registered")
    ) {
        return "This email is already registered. Log in or reset the password.";
    }
    if (code === "signup_disabled" || text.includes("signups not allowed")) {
        return "New registrations are not available right now.";
    }
    if (text.includes("code verifier") || code.includes("pkce")) {
        return "Open this link in the same browser where you requested it, or request a new link.";
    }
    return fallback;
}

export function authMessageCoverage() {
    const languages = Object.keys(DIRECTIONS).filter((language) => language !== "en");
    const missing = [];
    for (const [english, row] of Object.entries(MESSAGES)) {
        for (const language of languages) {
            if (!row[language]) missing.push(language + ":" + english);
        }
    }
    return { keys: Object.keys(MESSAGES).length, languages: languages.length, missing };
}
