      NEW.status := 'pending';
    END IF;
    IF NEW.currency IS NULL THEN
      NEW.currency := 'EUR';
    END IF;

    IF NEW.user_id IS DISTINCT FROM auth.uid()
       OR NEW.status IS DISTINCT FROM 'pending'
       OR NEW.driver_id IS NOT NULL
       OR NEW.price IS NOT NULL
       OR NEW.currency IS DISTINCT FROM 'EUR'
       OR NEW.accepted_at IS NOT NULL
       OR NEW.picked_up_at IS NOT NULL
       OR NEW.delivered_at IS NOT NULL
       OR NEW.cancelled_at IS NOT NULL THEN
      RAISE EXCEPTION 'customers can only create their own pending delivery request'
        USING ERRCODE = '42501';
    END IF;

    RETURN NEW;
  END IF;

  IF TG_OP = 'UPDATE' THEN
    IF NEW.cancelled_at IS NULL
       AND OLD.status = 'pending'
       AND OLD.driver_id IS NULL
       AND NEW.status = 'cancelled' THEN
      NEW.cancelled_at := now();
    END IF;

    IF OLD.user_id IS DISTINCT FROM auth.uid()
       OR OLD.status IS DISTINCT FROM 'pending'
       OR OLD.driver_id IS NOT NULL
       OR NEW.user_id IS DISTINCT FROM OLD.user_id
       OR NEW.driver_id IS DISTINCT FROM OLD.driver_id
       OR NEW.status IS DISTINCT FROM 'cancelled'
       OR NEW.price IS DISTINCT FROM OLD.price
       OR NEW.currency IS DISTINCT FROM OLD.currency
       OR NEW.pickup_address IS DISTINCT FROM OLD.pickup_address
       OR NEW.delivery_address IS DISTINCT FROM OLD.delivery_address
       OR NEW.package_details IS DISTINCT FROM OLD.package_details
       OR NEW.created_at IS DISTINCT FROM OLD.created_at
       OR NEW.id IS DISTINCT FROM OLD.id
       OR NEW.accepted_at IS DISTINCT FROM OLD.accepted_at
       OR NEW.picked_up_at IS DISTINCT FROM OLD.picked_up_at
       OR NEW.delivered_at IS DISTINCT FROM OLD.delivered_at
       OR OLD.cancelled_at IS NOT NULL
       OR NEW.cancelled_at IS NULL THEN
      RAISE EXCEPTION 'customers can only cancel their own unassigned pending delivery'
        USING ERRCODE = '42501';
    END IF;
  END IF;

  RETURN NEW;
END;
