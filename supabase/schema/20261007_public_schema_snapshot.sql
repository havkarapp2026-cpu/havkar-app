CREATE OR REPLACE FUNCTION public.enforce_ad_owner_write()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
BEGIN
  IF current_user = 'anon' THEN
    RAISE EXCEPTION 'anonymous users cannot create or change ads'
      USING ERRCODE = '42501';
  END IF;

  IF current_user = 'authenticated' THEN
    IF TG_OP = 'INSERT' THEN
      IF NEW.user_id IS DISTINCT FROM auth.uid() THEN
        RAISE EXCEPTION 'ads can only be created for the current user'
          USING ERRCODE = '42501';
      END IF;
    ELSIF TG_OP = 'UPDATE' THEN
      IF OLD.user_id IS DISTINCT FROM auth.uid()
         OR NEW.user_id IS DISTINCT FROM OLD.user_id THEN
        RAISE EXCEPTION 'users cannot change ad ownership'
          USING ERRCODE = '42501';
      END IF;
    ELSIF TG_OP = 'DELETE' THEN
      IF OLD.user_id IS DISTINCT FROM auth.uid() THEN
        RAISE EXCEPTION 'users cannot delete another user ad'
          USING ERRCODE = '42501';
      END IF;
      RETURN OLD;
    END IF;
  END IF;

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;

  RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.enforce_business_application_applicant_write()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
BEGIN
  IF current_user <> 'authenticated' THEN
    IF TG_OP = 'DELETE' THEN
      RETURN OLD;
    END IF;
    RETURN NEW;
  END IF;

  IF TG_OP = 'DELETE' THEN
    IF lower(COALESCE(OLD.status, '')) = 'approved' THEN
      RAISE EXCEPTION 'applicants cannot delete an approved business application'
        USING ERRCODE = '42501';
    END IF;
    RETURN OLD;
  END IF;

  IF TG_OP = 'INSERT' THEN
    IF NEW.status IS NULL THEN
      NEW.status := 'pending';
    END IF;

    IF NEW.user_id IS DISTINCT FROM auth.uid()
       OR NEW.status IS DISTINCT FROM 'pending'
       OR NEW.reviewed_at IS NOT NULL
       OR NEW.reviewed_by IS NOT NULL
       OR NEW.review_notes IS NOT NULL
       OR NEW.rejection_reason IS NOT NULL THEN
      RAISE EXCEPTION 'business applications must be submitted by the current user as pending without review fields'
        USING ERRCODE = '42501';
    END IF;

    RETURN NEW;
  END IF;

  IF TG_OP = 'UPDATE' THEN
    IF OLD.user_id IS DISTINCT FROM auth.uid()
       OR lower(COALESCE(OLD.status, '')) = 'approved'
       OR NEW.user_id IS DISTINCT FROM OLD.user_id
       OR NEW.status IS DISTINCT FROM 'pending'
       OR NEW.id IS DISTINCT FROM OLD.id
       OR NEW.created_at IS DISTINCT FROM OLD.created_at
       OR NEW.reviewed_at IS DISTINCT FROM OLD.reviewed_at
       OR NEW.reviewed_by IS DISTINCT FROM OLD.reviewed_by
       OR NEW.review_notes IS DISTINCT FROM OLD.review_notes
       OR NEW.rejection_reason IS DISTINCT FROM OLD.rejection_reason
       OR NEW.documents IS DISTINCT FROM OLD.documents THEN
      RAISE EXCEPTION 'applicants cannot change business application ownership, review fields, or an approved application'
        USING ERRCODE = '42501';
    END IF;
  END IF;

  RETURN NEW;
END;
$function$;

