CREATE OR REPLACE FUNCTION public.trade_crypto(p_user_id uuid, p_side text, p_symbol text, p_amount numeric, p_price_eur numeric)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_side text;
  v_symbol text;
  v_price numeric;
  v_crypto_amount numeric;
  v_eur_amount numeric;
  v_eur_wallet public.wallets%rowtype;
  v_crypto_wallet public.wallets%rowtype;
  v_trade_id uuid;
  v_created_at timestamptz;
BEGIN
  IF p_user_id IS NULL OR NOT EXISTS (
    SELECT 1 FROM auth.users WHERE id = p_user_id
  ) THEN
    RAISE EXCEPTION 'Invalid user';
  END IF;

  v_side := lower(trim(COALESCE(p_side, '')));
  IF v_side NOT IN ('buy', 'sell') THEN
    RAISE EXCEPTION 'Invalid trade side';
  END IF;

  v_symbol := upper(trim(COALESCE(p_symbol, '')));
  IF v_symbol NOT IN ('BTC', 'ETH', 'USDT', 'BNB', 'SOL', 'XRP', 'ADA', 'DOGE') THEN
    RAISE EXCEPTION 'Unsupported cryptocurrency';
  END IF;

  IF p_amount IS NULL
     OR p_amount <= 0
     OR p_amount <> p_amount
     OR p_amount = 'Infinity'::numeric
     OR p_amount = '-Infinity'::numeric
     OR p_amount <> trunc(p_amount, 18)
     OR p_amount >= 1000000000000000000
  THEN
    RAISE EXCEPTION 'Invalid crypto quantity';
  END IF;

  IF p_price_eur IS NULL
     OR p_price_eur <= 0
     OR p_price_eur <> p_price_eur
     OR p_price_eur = 'Infinity'::numeric
     OR p_price_eur = '-Infinity'::numeric
     OR p_price_eur <> trunc(p_price_eur, 18)
     OR p_price_eur >= 1000000000000000000
  THEN
    RAISE EXCEPTION 'Invalid execution price';
  END IF;

  v_crypto_amount := p_amount;
  v_price := p_price_eur;
  v_eur_amount := round(v_crypto_amount * v_price, 2);

  IF v_eur_amount IS NULL
     OR v_eur_amount <= 0
     OR v_eur_amount <> v_eur_amount
     OR v_eur_amount > 9999999999999999.99
  THEN
    RAISE EXCEPTION 'EUR amount is out of range';
  END IF;

  PERFORM 1
  FROM public.wallets
  WHERE user_id = p_user_id
    AND upper(currency) = 'EUR'
  FOR UPDATE;

  PERFORM 1
  FROM public.wallets
  WHERE user_id = p_user_id
    AND upper(currency) = v_symbol
  FOR UPDATE;

  SELECT *
  INTO v_eur_wallet
  FROM public.wallets
  WHERE user_id = p_user_id
    AND upper(currency) = 'EUR';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'EUR wallet not found';
  END IF;

  SELECT *
  INTO v_crypto_wallet
  FROM public.wallets
  WHERE user_id = p_user_id
    AND upper(currency) = v_symbol;

  IF v_side = 'buy' THEN
    UPDATE public.wallets
    SET balance = balance - v_eur_amount,
        updated_at = now()
    WHERE id = v_eur_wallet.id
      AND upper(currency) = 'EUR'
      AND balance >= v_eur_amount;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Insufficient EUR balance';
    END IF;

    IF v_crypto_wallet.id IS NULL THEN
      INSERT INTO public.wallets (user_id, currency, balance)
      VALUES (p_user_id, v_symbol, v_crypto_amount);
    ELSE
      UPDATE public.wallets
      SET balance = balance + v_crypto_amount,
          updated_at = now()
      WHERE id = v_crypto_wallet.id
        AND upper(currency) = v_symbol;

      IF NOT FOUND THEN
        RAISE EXCEPTION 'Crypto wallet not found';
      END IF;
    END IF;
  ELSE
    IF v_crypto_wallet.id IS NULL THEN
      RAISE EXCEPTION 'Crypto wallet not found';
    END IF;

    UPDATE public.wallets
    SET balance = balance - v_crypto_amount,
        updated_at = now()
    WHERE id = v_crypto_wallet.id
      AND upper(currency) = v_symbol
      AND balance >= v_crypto_amount;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Insufficient cryptocurrency balance';
    END IF;

    UPDATE public.wallets
    SET balance = balance + v_eur_amount,
        updated_at = now()
    WHERE id = v_eur_wallet.id
      AND upper(currency) = 'EUR';

    IF NOT FOUND THEN
      RAISE EXCEPTION 'EUR wallet not found';
    END IF;
  END IF;

  INSERT INTO public.crypto_trades (
    user_id,
    side,
    symbol,
    crypto_quantity,
    eur_amount,
    execution_price
  )
  VALUES (
    p_user_id,
    v_side,
    v_symbol,
    v_crypto_amount,
    v_eur_amount,
    v_price
  )
  RETURNING id, created_at
  INTO v_trade_id, v_created_at;

  RETURN jsonb_build_object(
    'success', true,
    'trade_id', v_trade_id,
    'side', v_side,
    'symbol', v_symbol,
    'crypto_quantity', v_crypto_amount,
    'eur_amount', v_eur_amount,
    'execution_price', v_price,
    'created_at', v_created_at
  );
END;
$function$;

