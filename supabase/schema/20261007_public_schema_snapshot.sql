CREATE OR REPLACE FUNCTION public.transfer_money(p_receiver_id uuid, p_amount numeric, p_note text DEFAULT NULL::text)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_sender_id uuid;
  v_sender_wallet uuid;
  v_receiver_wallet uuid;
  v_transfer_id uuid;
BEGIN
  v_sender_id := auth.uid();

  IF v_sender_id IS NULL THEN
    RAISE EXCEPTION 'NOT_AUTHENTICATED';
  END IF;

  IF p_receiver_id IS NULL THEN
    RAISE EXCEPTION 'INVALID_RECEIVER';
  END IF;

  IF p_receiver_id = v_sender_id THEN
    RAISE EXCEPTION 'CANNOT_SEND_TO_YOURSELF';
  END IF;

  IF p_amount IS NULL
     OR p_amount <= 0
     OR p_amount <> p_amount
     OR p_amount = 'Infinity'::numeric
     OR p_amount = '-Infinity'::numeric
     OR p_amount <> trunc(p_amount, 2)
     OR p_amount > 9999999999999999.99
  THEN
    RAISE EXCEPTION 'INVALID_AMOUNT';
  END IF;

  PERFORM 1
  FROM public.wallets
  WHERE user_id IN (v_sender_id, p_receiver_id)
    AND currency = 'EUR'
  ORDER BY user_id
  FOR UPDATE;

  SELECT id
  INTO v_sender_wallet
  FROM public.wallets
  WHERE user_id = v_sender_id
    AND currency = 'EUR';

  SELECT id
  INTO v_receiver_wallet
  FROM public.wallets
  WHERE user_id = p_receiver_id
    AND currency = 'EUR';

  IF v_sender_wallet IS NULL THEN
    RAISE EXCEPTION 'SENDER_WALLET_NOT_FOUND';
  END IF;

  IF v_receiver_wallet IS NULL THEN
    RAISE EXCEPTION 'RECEIVER_WALLET_NOT_FOUND';
  END IF;

  UPDATE public.wallets
  SET balance = balance - p_amount,
      updated_at = now()
  WHERE id = v_sender_wallet
    AND currency = 'EUR'
    AND balance >= p_amount;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'INSUFFICIENT_BALANCE';
  END IF;

  UPDATE public.wallets
  SET balance = balance + p_amount,
      updated_at = now()
  WHERE id = v_receiver_wallet
    AND currency = 'EUR';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'RECEIVER_WALLET_NOT_FOUND';
  END IF;

  INSERT INTO public.wallet_transfers (
    sender_id,
    receiver_id,
    amount,
    currency
  )
  VALUES (
    v_sender_id,
    p_receiver_id,
    p_amount,
    'EUR'
  )
  RETURNING id INTO v_transfer_id;

  RETURN json_build_object(
    'success', true,
    'transfer_id', v_transfer_id,
    'amount', p_amount,
    'currency', 'EUR'
  );
END;
$function$;

CREATE OR REPLACE FUNCTION public.update_delivery_status(p_delivery_id bigint, p_new_status text)
 RETURNS delivery_requests
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_current_status text;
  v_delivery public.delivery_requests;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.driver_applications
    WHERE user_id = auth.uid()
      AND status = 'approved'
  ) THEN
    RAISE EXCEPTION 'Approved driver account required';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.delivery_requests
    WHERE id = p_delivery_id
      AND user_id = auth.uid()
  ) THEN
    RAISE EXCEPTION 'Customers cannot update their own delivery as a driver';
  END IF;

  SELECT status
  INTO v_current_status
  FROM public.delivery_requests
  WHERE id = p_delivery_id
    AND driver_id = auth.uid()
    AND user_id IS DISTINCT FROM auth.uid()
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Delivery is not assigned to this driver';
  END IF;

  IF NOT (
    (v_current_status = 'accepted' AND p_new_status = 'picked_up')
    OR (v_current_status = 'picked_up' AND p_new_status = 'in_transit')
    OR (v_current_status = 'in_transit' AND p_new_status = 'delivered')
  ) THEN
    RAISE EXCEPTION 'Invalid delivery status transition';
  END IF;

  UPDATE public.delivery_requests
  SET
    status = p_new_status,
    picked_up_at = CASE
      WHEN p_new_status = 'picked_up' THEN now()
      ELSE picked_up_at
    END,
    delivered_at = CASE
      WHEN p_new_status = 'delivered' THEN now()
      ELSE delivered_at
    END,
    updated_at = now()
  WHERE id = p_delivery_id
    AND driver_id = auth.uid()
    AND user_id IS DISTINCT FROM auth.uid()
  RETURNING *
  INTO v_delivery;

  RETURN v_delivery;
END;
$function$;

