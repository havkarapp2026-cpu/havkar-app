CREATE OR REPLACE FUNCTION public.havkar_owner_list_recent_event_tickets(p_limit integer DEFAULT 50)
RETURNS TABLE (
  id bigint,
  ticket_code text,
  ticket_type text,
  ticket_status text,
  payment_status text,
  event_id bigint,
  event_title text,
  quantity integer,
  total_amount numeric,
  currency text,
  checked_in_at timestamptz,
  cancelled_at timestamptz,
  created_at timestamptz,
  user_id uuid
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  lim integer := GREATEST(1, LEAST(COALESCE(p_limit, 50), 200));
BEGIN
  IF NOT havkar_private.caller_is_owner() AND NOT havkar_private.caller_is_admin() THEN
    RAISE EXCEPTION 'not authorized' USING ERRCODE = '42501';
  END IF;

  RETURN QUERY
  SELECT t.id, t.ticket_code, t.ticket_type, t.ticket_status, t.payment_status, t.event_id,
         e.title, t.quantity, t.total_amount, t.currency, t.checked_in_at, t.cancelled_at,
         t.created_at, t.user_id
  FROM public.event_tickets t
  LEFT JOIN public.events e ON e.id = t.event_id
  ORDER BY t.created_at DESC
  LIMIT lim;
END;
$$;

