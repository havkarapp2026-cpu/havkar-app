-- Operational event tickets: unique codes, holds, check-in, audit.
-- Does not alter owner_identity.

ALTER TABLE public.event_tickets
  ADD COLUMN IF NOT EXISTS ticket_code text,
  ADD COLUMN IF NOT EXISTS ticket_type text NOT NULL DEFAULT 'general',
  ADD COLUMN IF NOT EXISTS hold_expires_at timestamptz,
  ADD COLUMN IF NOT EXISTS checked_in_at timestamptz,
  ADD COLUMN IF NOT EXISTS checked_in_by uuid,
  ADD COLUMN IF NOT EXISTS cancelled_at timestamptz,
  ADD COLUMN IF NOT EXISTS cancel_reason text;

UPDATE public.event_tickets
SET ticket_code = upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 12))
WHERE ticket_code IS NULL;

ALTER TABLE public.event_tickets
  ALTER COLUMN ticket_code SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS event_tickets_ticket_code_uidx
  ON public.event_tickets (ticket_code);

ALTER TABLE public.event_tickets
  DROP CONSTRAINT IF EXISTS event_tickets_ticket_type_check;

ALTER TABLE public.event_tickets
  ADD CONSTRAINT event_tickets_ticket_type_check
  CHECK (ticket_type = ANY (ARRAY['general'::text, 'vip'::text, 'free'::text, 'early'::text]));

CREATE TABLE IF NOT EXISTS public.event_ticket_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id bigint NOT NULL REFERENCES public.event_tickets(id) ON DELETE CASCADE,
  event_id bigint NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
  actor_user_id uuid,
  action text NOT NULL,
  detail jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.event_ticket_events ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "ticket events readable by parties" ON public.event_ticket_events;
CREATE POLICY "ticket events readable by parties"
  ON public.event_ticket_events
  FOR SELECT
  TO authenticated
  USING (
    actor_user_id = auth.uid()
    OR EXISTS (
      SELECT 1 FROM public.event_tickets t
      WHERE t.id = ticket_id AND t.user_id = auth.uid()
    )
    OR EXISTS (
      SELECT 1 FROM public.events e
      WHERE e.id = event_id AND e.user_id = auth.uid()
    )
    OR havkar_private.caller_is_owner()
    OR havkar_private.caller_is_admin()
  );

CREATE OR REPLACE FUNCTION public.havkar_event_occupied_seats(p_event_id bigint)
RETURNS integer
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT COALESCE(SUM(t.quantity), 0)::integer
  FROM public.event_tickets t
  WHERE t.event_id = p_event_id
    AND (
      (t.ticket_status = 'valid' AND t.payment_status = 'paid')
      OR (
        t.ticket_status = 'pending'
        AND t.payment_status = 'pending'
        AND (t.hold_expires_at IS NULL OR t.hold_expires_at > now())
      )
    )
    AND t.cancelled_at IS NULL;
$$;

CREATE OR REPLACE FUNCTION public.havkar_check_in_event_ticket(p_ticket_code text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  actor uuid := auth.uid();
  ticket public.event_tickets%ROWTYPE;
  event_row public.events%ROWTYPE;
BEGIN
  IF actor IS NULL THEN
    RAISE EXCEPTION 'not authenticated' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO ticket
  FROM public.event_tickets
  WHERE ticket_code = upper(trim(p_ticket_code))
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'ticket not found' USING ERRCODE = 'P0002';
  END IF;

  SELECT * INTO event_row FROM public.events WHERE id = ticket.event_id;

  IF event_row.user_id IS DISTINCT FROM actor
     AND NOT havkar_private.caller_is_owner()
     AND NOT havkar_private.caller_is_admin() THEN
    RAISE EXCEPTION 'not authorized' USING ERRCODE = '42501';
  END IF;

  IF ticket.cancelled_at IS NOT NULL OR ticket.ticket_status = 'cancelled' THEN
    RAISE EXCEPTION 'ticket cancelled' USING ERRCODE = '22023';
  END IF;

  IF ticket.ticket_status IS DISTINCT FROM 'valid' OR ticket.payment_status IS DISTINCT FROM 'paid' THEN
    RAISE EXCEPTION 'ticket not valid for entry' USING ERRCODE = '22023';
  END IF;

  IF ticket.checked_in_at IS NOT NULL THEN
    RETURN jsonb_build_object(
      'ok', false,
      'code', 'ALREADY_CHECKED_IN',
      'checked_in_at', ticket.checked_in_at,
      'ticket_code', ticket.ticket_code
    );
  END IF;

  UPDATE public.event_tickets
  SET checked_in_at = now(),
      checked_in_by = actor
  WHERE id = ticket.id;

  INSERT INTO public.event_ticket_events (ticket_id, event_id, actor_user_id, action, detail)
  VALUES (
    ticket.id,
    ticket.event_id,
    actor,
    'check_in',
    jsonb_build_object('ticket_code', ticket.ticket_code)
  );

  RETURN jsonb_build_object(
    'ok', true,
    'ticket_id', ticket.id,
    'ticket_code', ticket.ticket_code,
    'checked_in_at', now()
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.havkar_cancel_event_ticket(p_ticket_id bigint, p_reason text DEFAULT NULL)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  actor uuid := auth.uid();
  ticket public.event_tickets%ROWTYPE;
  event_row public.events%ROWTYPE;
BEGIN
  IF actor IS NULL THEN
    RAISE EXCEPTION 'not authenticated' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO ticket FROM public.event_tickets WHERE id = p_ticket_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'ticket not found' USING ERRCODE = 'P0002';
  END IF;

  SELECT * INTO event_row FROM public.events WHERE id = ticket.event_id;

  IF ticket.user_id IS DISTINCT FROM actor
     AND event_row.user_id IS DISTINCT FROM actor
     AND NOT havkar_private.caller_is_owner()
     AND NOT havkar_private.caller_is_admin() THEN
    RAISE EXCEPTION 'not authorized' USING ERRCODE = '42501';
  END IF;

  IF ticket.checked_in_at IS NOT NULL THEN
    RAISE EXCEPTION 'checked-in ticket cannot be cancelled' USING ERRCODE = '22023';
  END IF;

  UPDATE public.event_tickets
  SET ticket_status = 'cancelled',
      cancelled_at = now(),
      cancel_reason = NULLIF(trim(COALESCE(p_reason, '')), '')
  WHERE id = ticket.id;

  INSERT INTO public.event_ticket_events (ticket_id, event_id, actor_user_id, action, detail)
  VALUES (
    ticket.id,
    ticket.event_id,
    actor,
    'cancel',
    jsonb_build_object('reason', p_reason)
  );

  RETURN jsonb_build_object('ok', true, 'ticket_id', ticket.id, 'ticket_status', 'cancelled');
END;
$$;

CREATE OR REPLACE FUNCTION public.havkar_list_event_tickets_for_organizer(p_event_id bigint)
RETURNS TABLE (
  id bigint,
  ticket_code text,
  ticket_type text,
  ticket_status text,
  payment_status text,
  quantity integer,
  checked_in_at timestamptz,
  created_at timestamptz,
  user_id uuid
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE actor uuid := auth.uid();
BEGIN
  IF actor IS NULL THEN
    RAISE EXCEPTION 'not authenticated' USING ERRCODE = '42501';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.events e
    WHERE e.id = p_event_id
      AND (
        e.user_id = actor
        OR havkar_private.caller_is_owner()
        OR havkar_private.caller_is_admin()
      )
  ) THEN
    RAISE EXCEPTION 'not authorized' USING ERRCODE = '42501';
  END IF;

  RETURN QUERY
  SELECT t.id, t.ticket_code, t.ticket_type, t.ticket_status, t.payment_status,
         t.quantity, t.checked_in_at, t.created_at, t.user_id
  FROM public.event_tickets t
  WHERE t.event_id = p_event_id
  ORDER BY t.created_at DESC;
END;
$$;

