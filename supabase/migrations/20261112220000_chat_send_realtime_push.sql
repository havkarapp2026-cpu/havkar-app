-- Chat send idempotency, recipient in-app notifications, push token registry.
-- Does not enable payment collection. Does not invent delivery/read receipts.

ALTER TABLE public.messages
  ADD COLUMN IF NOT EXISTS client_message_id uuid;

CREATE UNIQUE INDEX IF NOT EXISTS messages_client_message_id_uidx
  ON public.messages (sender_id, client_message_id)
  WHERE client_message_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.havkar_push_device_tokens (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  platform text NOT NULL
    CHECK (platform = ANY (ARRAY['web','android','ios'])),
  endpoint text NOT NULL,
  p256dh text,
  auth_secret text,
  fcm_token text,
  user_agent text,
  permission_state text NOT NULL DEFAULT 'granted',
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  revoked_at timestamptz,
  CONSTRAINT havkar_push_endpoint_unique UNIQUE (endpoint)
);

CREATE INDEX IF NOT EXISTS havkar_push_user_active_idx
  ON public.havkar_push_device_tokens (user_id)
  WHERE revoked_at IS NULL;

ALTER TABLE public.havkar_push_device_tokens ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.havkar_push_device_tokens FROM PUBLIC, anon;
GRANT SELECT, INSERT, UPDATE ON TABLE public.havkar_push_device_tokens TO authenticated;

DROP POLICY IF EXISTS havkar_push_tokens_owner ON public.havkar_push_device_tokens;
CREATE POLICY havkar_push_tokens_owner
ON public.havkar_push_device_tokens
FOR ALL TO authenticated
USING (user_id = auth.uid())
WITH CHECK (user_id = auth.uid());

-- Atomic send: persist message + in-app notification for peer. Idempotent.
CREATE OR REPLACE FUNCTION public.havkar_send_chat_message(
  p_conversation_id uuid,
  p_message_text text,
  p_client_message_id uuid DEFAULT NULL
)
RETURNS public.messages
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  uid uuid := auth.uid();
  conv public.conversations%ROWTYPE;
  existing public.messages%ROWTYPE;
  inserted public.messages%ROWTYPE;
  peer_id uuid;
  preview text;
BEGIN
  IF uid IS NULL THEN
    RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '42501';
  END IF;

  IF p_message_text IS NULL OR length(trim(p_message_text)) = 0 THEN
    RAISE EXCEPTION 'empty_message' USING ERRCODE = '22023';
  END IF;

  IF length(p_message_text) > 4000 THEN
    RAISE EXCEPTION 'message_too_long' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO conv
  FROM public.conversations c
  WHERE c.id = p_conversation_id
    AND (c.buyer_id = uid OR c.seller_id = uid);

  IF conv.id IS NULL THEN
    RAISE EXCEPTION 'not_conversation_party' USING ERRCODE = '42501';
  END IF;

  IF p_client_message_id IS NOT NULL THEN
    SELECT * INTO existing
    FROM public.messages m
    WHERE m.sender_id = uid
      AND m.client_message_id = p_client_message_id;

    IF existing.id IS NOT NULL THEN
      RETURN existing;
    END IF;
  END IF;

  INSERT INTO public.messages (
    conversation_id,
    sender_id,
    message_text,
    is_read,
    client_message_id
  ) VALUES (
    p_conversation_id,
    uid,
    trim(p_message_text),
    false,
    p_client_message_id
  )
  RETURNING * INTO inserted;

  UPDATE public.conversations
  SET updated_at = now()
  WHERE id = p_conversation_id;

  peer_id := CASE
    WHEN conv.buyer_id = uid THEN conv.seller_id
    ELSE conv.buyer_id
  END;

  preview := left(trim(p_message_text), 140);

  IF peer_id IS NOT NULL THEN
    INSERT INTO public.notifications (
      user_id,
      type,
      title,
      message,
      is_read,
      action_url,
      reference_id,
      metadata
    ) VALUES (
      peer_id,
      'chat_message',
      'New HAVKAR message',
      preview,
      false,
      '/chat.html?conversation_id=' || p_conversation_id::text,
      inserted.id::text,
      jsonb_build_object(
        'conversation_id', p_conversation_id,
        'message_id', inserted.id,
        'sender_id', uid
      )
    );
  END IF;

  RETURN inserted;
END;
$$;

REVOKE ALL ON FUNCTION public.havkar_send_chat_message(uuid, text, uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.havkar_send_chat_message(uuid, text, uuid) TO authenticated;

-- Ensure conversations are in realtime publication for inbox bump (safe if already added).
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime'
      AND schemaname = 'public'
      AND tablename = 'conversations'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.conversations;
  END IF;
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'conversations realtime publication skipped: %', SQLERRM;
END $$;

ALTER TABLE public.conversations REPLICA IDENTITY FULL;
