-- Extend service booking statuses for refund/dispute settlement.
-- Additive only; preserves existing rows.

ALTER TABLE public.service_bookings
  DROP CONSTRAINT IF EXISTS service_booking_status_check;

ALTER TABLE public.service_bookings
  ADD CONSTRAINT service_booking_status_check
  CHECK (
    status IN (
      'pending',
      'price_proposed',
      'accepted',
      'declined',
      'cancelled',
      'completion_requested',
      'completed',
      'in_review',
      'refunded',
      'disputed'
    )
  );

ALTER TABLE public.service_bookings
  ADD COLUMN IF NOT EXISTS stripe_payment_intent text,
  ADD COLUMN IF NOT EXISTS stripe_charge_id text,
  ADD COLUMN IF NOT EXISTS refunded_at timestamptz,
  ADD COLUMN IF NOT EXISTS disputed_at timestamptz;

CREATE TABLE IF NOT EXISTS public.service_settlement_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id bigint REFERENCES public.service_bookings(id) ON DELETE SET NULL,
  stripe_event_id text UNIQUE,
  event_type text NOT NULL,
  outcome text,
  amount integer,
  currency text,
  meta jsonb DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.service_settlement_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.service_settlement_events FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.service_settlement_events TO authenticated;
GRANT ALL ON TABLE public.service_settlement_events TO service_role;

DROP POLICY IF EXISTS service_settlement_events_party_select ON public.service_settlement_events;
CREATE POLICY service_settlement_events_party_select
ON public.service_settlement_events
FOR SELECT
TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM public.service_bookings b
    WHERE b.id = service_settlement_events.booking_id
      AND (b.customer_id = auth.uid() OR b.provider_id = auth.uid())
  )
  OR COALESCE(havkar_private.caller_is_admin(), false)
);
