-- Audited reassignment of a pending business application to another auth user.
-- Does not approve, reject, or invent verification evidence.
-- Intended for authorized ownership correction only.

CREATE TABLE IF NOT EXISTS public.business_application_ownership_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id bigint NOT NULL REFERENCES public.business_applications (id) ON DELETE CASCADE,
  from_user_id uuid,
  to_user_id uuid NOT NULL,
  actor text NOT NULL DEFAULT 'service',
  reason text NOT NULL,
  meta jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now())
);

ALTER TABLE public.business_application_ownership_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.business_application_ownership_events FORCE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.business_application_ownership_events FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.business_application_ownership_events TO authenticated;
GRANT ALL ON TABLE public.business_application_ownership_events TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.business_application_ownership_events_id_seq TO authenticated, service_role;

DROP POLICY IF EXISTS business_ownership_events_select ON public.business_application_ownership_events;
CREATE POLICY business_ownership_events_select
ON public.business_application_ownership_events
FOR SELECT
TO authenticated
USING (
  COALESCE(havkar_private.caller_is_admin(), false)
  OR from_user_id = (SELECT auth.uid())
  OR to_user_id = (SELECT auth.uid())
);

CREATE OR REPLACE FUNCTION public.reassign_business_application_owner(
  p_application_id bigint,
  p_to_user_id uuid,
  p_reason text
)
RETURNS public.business_applications
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  app public.business_applications;
  previous_user uuid;
  previous_email text;
  target_email text;
  existing_count integer;
BEGIN
  IF p_application_id IS NULL OR p_to_user_id IS NULL THEN
    RAISE EXCEPTION 'application and target user are required' USING ERRCODE = '22023';
  END IF;

  IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
    RAISE EXCEPTION 'reason is required' USING ERRCODE = '22023';
  END IF;

  -- Clients must not call this directly; service/postgres only.
  IF current_user = 'authenticated' OR current_user = 'anon' THEN
    RAISE EXCEPTION 'privileged ownership reassignment required'
      USING ERRCODE = '42501';
  END IF;

  SELECT * INTO app
  FROM public.business_applications
  WHERE id = p_application_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'business application not found' USING ERRCODE = 'P0002';
  END IF;

  IF lower(COALESCE(app.status, '')) = 'approved' THEN
    RAISE EXCEPTION 'approved applications cannot be reassigned'
      USING ERRCODE = '42501';
  END IF;

  previous_user := app.user_id;
  previous_email := app.email;

  IF previous_user = p_to_user_id THEN
    RETURN app;
  END IF;

  SELECT u.email INTO target_email
  FROM auth.users u
  WHERE u.id = p_to_user_id;

  IF target_email IS NULL THEN
    RAISE EXCEPTION 'target user not found' USING ERRCODE = 'P0002';
  END IF;

  SELECT count(*)::integer INTO existing_count
  FROM public.business_applications
  WHERE user_id = p_to_user_id
    AND id IS DISTINCT FROM p_application_id;

  IF existing_count > 0 THEN
    RAISE EXCEPTION 'target user already has a business application'
      USING ERRCODE = '23505';
  END IF;

  UPDATE public.business_applications
  SET
    user_id = p_to_user_id,
    email = target_email,
    updated_at = timezone('utc', now())
  WHERE id = app.id
  RETURNING * INTO app;

  UPDATE public.business_application_documents
  SET user_id = p_to_user_id
  WHERE application_id = app.id
    AND user_id IS DISTINCT FROM p_to_user_id;

  INSERT INTO public.business_application_ownership_events (
    application_id, from_user_id, to_user_id, actor, reason, meta
  ) VALUES (
    app.id,
    previous_user,
    p_to_user_id,
    current_user,
    btrim(p_reason),
    jsonb_build_object(
      'previous_contact_email', previous_email,
      'contact_email_set_to', target_email,
      'status_unchanged', app.status
    )
  );

  RETURN app;
END;
$$;

REVOKE ALL ON FUNCTION public.reassign_business_application_owner(bigint, uuid, text)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.reassign_business_application_owner(bigint, uuid, text)
  TO service_role;
