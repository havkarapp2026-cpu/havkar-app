-- Seller follows for Buy & Sell social discovery.
-- Authenticated users may follow/unfollow sellers. Public read of follow counts is allowed.

CREATE TABLE IF NOT EXISTS public.seller_follows (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  follower_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  seller_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT seller_follows_follower_seller_key UNIQUE (follower_id, seller_id),
  CONSTRAINT seller_follows_not_self CHECK (follower_id <> seller_id)
);

CREATE INDEX IF NOT EXISTS seller_follows_seller_id_idx
  ON public.seller_follows USING btree (seller_id);

CREATE INDEX IF NOT EXISTS seller_follows_follower_id_idx
  ON public.seller_follows USING btree (follower_id);

ALTER TABLE public.seller_follows ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Anyone can read seller follows" ON public.seller_follows;
CREATE POLICY "Anyone can read seller follows"
  ON public.seller_follows
  AS PERMISSIVE
  FOR SELECT
  TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "Users can follow sellers" ON public.seller_follows;
CREATE POLICY "Users can follow sellers"
  ON public.seller_follows
  AS PERMISSIVE
  FOR INSERT
  TO authenticated
  WITH CHECK (auth.uid() = follower_id AND follower_id <> seller_id);

DROP POLICY IF EXISTS "Users can unfollow sellers" ON public.seller_follows;
CREATE POLICY "Users can unfollow sellers"
  ON public.seller_follows
  AS PERMISSIVE
  FOR DELETE
  TO authenticated
  USING (auth.uid() = follower_id);

REVOKE ALL ON TABLE public.seller_follows FROM PUBLIC;
GRANT SELECT, INSERT, DELETE ON TABLE public.seller_follows TO anon, authenticated;
GRANT ALL ON TABLE public.seller_follows TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.seller_follows_id_seq TO anon, authenticated, service_role;
