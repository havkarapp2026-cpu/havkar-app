CREATE TABLE IF NOT EXISTS public.service_refund_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id bigint NOT NULL REFERENCES public.service_bookings(id) ON DELETE RESTRICT,
  requested_by uuid NOT NULL,
  refund_cents integer NOT NULL CHECK (refund_cents > 0),
  currency text NOT NULL,
  reason text,
  status text NOT NULL DEFAULT 'prepared'
    CHECK (status = ANY (ARRAY[
      'prepared'::text,
      'owner_approved'::text,
      'executed'::text,
      'rejected'::text,
      'cancelled'::text
    ])),
  stripe_refund_id text,
  stripe_event_id text UNIQUE,
  plan jsonb NOT NULL DEFAULT '{}'::jsonb,
  owner_approved_by uuid,
  owner_approved_at timestamptz,
  executed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS service_refund_requests_one_open_per_booking
  ON public.service_refund_requests (booking_id)
  WHERE status IN ('prepared', 'owner_approved');

