CREATE OR REPLACE FUNCTION public.havkar_user_ops_role(target_user uuid)
RETURNS text
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE r text;
BEGIN
  IF target_user IS NULL THEN RETURN NULL; END IF;
  IF EXISTS (
    SELECT 1 FROM havkar_private.owner_identity o
    WHERE o.singleton AND o.user_id = target_user
  ) THEN
    RETURN 'owner';
  END IF;
  SELECT assignment.role INTO r
  FROM havkar_private.role_assignments assignment
  WHERE assignment.user_id = target_user
  ORDER BY CASE assignment.role
    WHEN 'admin' THEN 1
    WHEN 'staff' THEN 2
    WHEN 'support' THEN 3
    ELSE 9
  END
  LIMIT 1;
  RETURN COALESCE(r, 'user');
END;
$function$;

REVOKE ALL ON FUNCTION public.havkar_user_ops_role(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.havkar_user_ops_role(uuid) TO service_role, authenticated;
