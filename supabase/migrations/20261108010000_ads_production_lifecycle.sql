-- 1) Advertiser entitlement: approved business_applications only.
CREATE OR REPLACE FUNCTION havkar_private.caller_is_approved_advertiser()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.business_applications ba
    WHERE ba.user_id = (SELECT auth.uid())
      AND lower(ba.status) = 'approved'
  );
$$;

REVOKE ALL ON FUNCTION havkar_private.caller_is_approved_advertiser() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION havkar_private.caller_is_approved_advertiser() TO authenticated;

