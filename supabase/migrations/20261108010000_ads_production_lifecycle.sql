CREATE OR REPLACE FUNCTION public.record_ad_audit_event(
  p_ad_id bigint,
  p_action text,
  p_meta jsonb DEFAULT '{}'::jsonb
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF (SELECT auth.uid()) IS NULL THEN
    RAISE EXCEPTION 'authentication required' USING ERRCODE = '42501';
  END IF;
  INSERT INTO public.ad_audit_events (ad_id, actor_id, action, meta)
  VALUES (
    p_ad_id,
    (SELECT auth.uid()),
    left(btrim(COALESCE(p_action, '')), 80),
    COALESCE(p_meta, '{}'::jsonb)
  );
END;
$$;

