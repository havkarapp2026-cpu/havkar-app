CREATE OR REPLACE FUNCTION public.record_ad_metric_event(
  p_ad_id bigint,
  p_event_type text
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  uid uuid := (SELECT auth.uid());
  rate_key text;
  window_start timestamptz;
  hits integer;
  max_hits constant integer := 60;
BEGIN
  IF uid IS NULL THEN
    RETURN false;
  END IF;
  IF p_event_type NOT IN ('impression', 'click') THEN
    RAISE EXCEPTION 'invalid metric event' USING ERRCODE = '23514';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.ads a
    WHERE a.id = p_ad_id
      AND a.listing_surface = 'advertising'
      AND lower(COALESCE(a.status, '')) = 'active'
  ) THEN
    RETURN false;
  END IF;

  rate_key := uid::text || ':' || p_event_type || ':' ||
    to_char(timezone('utc', now()), 'YYYYMMDDHH24MI');

  SELECT window_started_at, hit_count
    INTO window_start, hits
  FROM public.ad_rate_buckets
  WHERE bucket_key = rate_key
  FOR UPDATE;

  IF NOT FOUND THEN
    INSERT INTO public.ad_rate_buckets (bucket_key, window_started_at, hit_count)
    VALUES (rate_key, timezone('utc', now()), 1);
  ELSE
    IF hits >= max_hits THEN
      RETURN false;
    END IF;
    UPDATE public.ad_rate_buckets
    SET hit_count = hit_count + 1
    WHERE bucket_key = rate_key;
  END IF;

  INSERT INTO public.ad_metric_events (ad_id, viewer_id, event_type)
  VALUES (p_ad_id, uid, p_event_type);

  RETURN true;
END;
$$;

REVOKE ALL ON FUNCTION public.record_ad_metric_event(bigint, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.record_ad_metric_event(bigint, text) TO authenticated;

CREATE OR REPLACE FUNCTION public.create_ad_report(
  p_ad_id bigint,
  p_reason text,
  p_details text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  uid uuid := (SELECT auth.uid());
  new_id bigint;
BEGIN
  IF uid IS NULL THEN
    RAISE EXCEPTION 'authentication required' USING ERRCODE = '42501';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.ads
    WHERE id = p_ad_id AND listing_surface = 'advertising'
  ) THEN
    RAISE EXCEPTION 'advertisement not found' USING ERRCODE = 'P0002';
  END IF;

  INSERT INTO public.ad_reports (ad_id, reporter_id, reason, details)
  VALUES (p_ad_id, uid, btrim(p_reason), NULLIF(btrim(COALESCE(p_details, '')), ''))
  ON CONFLICT (ad_id, reporter_id) DO UPDATE
    SET reason = EXCLUDED.reason,
        details = EXCLUDED.details,
        status = 'open',
        created_at = now()
  RETURNING id INTO new_id;

  UPDATE public.ads
  SET reported_count = COALESCE(reported_count, 0) + 1
  WHERE id = p_ad_id;

  PERFORM public.record_ad_audit_event(
    p_ad_id,
    'report_created',
    jsonb_build_object('report_id', new_id)
  );

  RETURN new_id;
END;
$$;

REVOKE ALL ON FUNCTION public.create_ad_report(bigint, text, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.create_ad_report(bigint, text, text) TO authenticated;

