-- 11) Admin moderation RPC (JWT app_metadata.role = admin).
CREATE OR REPLACE FUNCTION public.moderate_advertisement(
  p_ad_id bigint,
  p_decision text,
  p_notes text DEFAULT NULL
)
RETURNS public.ads
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  decision text := lower(btrim(COALESCE(p_decision, '')));
  row public.ads;
BEGIN
  IF NOT havkar_private.caller_is_admin() THEN
    RAISE EXCEPTION 'admin role required' USING ERRCODE = '42501';
  END IF;
  IF decision NOT IN ('approve', 'reject', 'pause') THEN
    RAISE EXCEPTION 'invalid moderation decision' USING ERRCODE = '23514';
  END IF;

  UPDATE public.ads
  SET
    status = CASE decision
      WHEN 'approve' THEN 'active'
      WHEN 'reject' THEN 'rejected'
      WHEN 'pause' THEN 'paused'
    END,
    moderation_notes = NULLIF(btrim(COALESCE(p_notes, '')), '')
  WHERE id = p_ad_id
    AND listing_surface = 'advertising'
  RETURNING * INTO row;

  IF row.id IS NULL THEN
    RAISE EXCEPTION 'advertisement not found' USING ERRCODE = 'P0002';
  END IF;

  INSERT INTO public.ad_audit_events (ad_id, actor_id, action, meta)
  VALUES (
    p_ad_id,
    (SELECT auth.uid()),
    'moderation_' || decision,
    jsonb_build_object('notes', p_notes)
  );

  RETURN row;
END;
$$;

REVOKE ALL ON FUNCTION public.moderate_advertisement(bigint, text, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.moderate_advertisement(bigint, text, text) TO authenticated;
