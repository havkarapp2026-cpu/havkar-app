-- Jobs applicant profiles + Services operations tables.
-- Additive. Does not enable live payments.

CREATE TABLE IF NOT EXISTS public.job_applicant_profiles (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  headline text,
  summary text,
  skills text,
  location text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT job_applicant_profiles_headline_len CHECK (
    headline IS NULL OR char_length(headline) BETWEEN 2 AND 120
  ),
  CONSTRAINT job_applicant_profiles_summary_len CHECK (
    summary IS NULL OR char_length(summary) <= 3000
  )
);

ALTER TABLE public.job_applicant_profiles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS job_applicant_profiles_select_own ON public.job_applicant_profiles;
CREATE POLICY job_applicant_profiles_select_own
  ON public.job_applicant_profiles FOR SELECT TO authenticated
  USING (user_id = auth.uid());

DROP POLICY IF EXISTS job_applicant_profiles_upsert_own ON public.job_applicant_profiles;
CREATE POLICY job_applicant_profiles_upsert_own
  ON public.job_applicant_profiles FOR ALL TO authenticated
  USING (user_id = auth.uid())
  WITH CHECK (user_id = auth.uid());

CREATE TABLE IF NOT EXISTS public.service_availability (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  service_id bigint REFERENCES public.services(id) ON DELETE CASCADE,
  slot_date date NOT NULL,
  start_time time NOT NULL,
  end_time time NOT NULL,
  is_available boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT service_availability_range CHECK (start_time < end_time)
);

CREATE INDEX IF NOT EXISTS service_availability_provider_date_idx
  ON public.service_availability (provider_id, slot_date);

ALTER TABLE public.service_availability ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS service_availability_select ON public.service_availability;
CREATE POLICY service_availability_select
  ON public.service_availability FOR SELECT TO authenticated
  USING (true);

DROP POLICY IF EXISTS service_availability_write_own ON public.service_availability;
CREATE POLICY service_availability_write_own
  ON public.service_availability FOR ALL TO authenticated
  USING (provider_id = auth.uid())
  WITH CHECK (provider_id = auth.uid());

CREATE TABLE IF NOT EXISTS public.service_milestones (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id bigint NOT NULL REFERENCES public.service_bookings(id) ON DELETE CASCADE,
  title text NOT NULL,
  amount numeric NOT NULL CHECK (amount >= 0),
  status text NOT NULL DEFAULT 'pending',
  created_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  CONSTRAINT service_milestones_status_check CHECK (
    status = ANY (ARRAY['pending'::text, 'completed'::text, 'cancelled'::text])
  ),
  CONSTRAINT service_milestones_title_len CHECK (char_length(title) BETWEEN 2 AND 120)
);

ALTER TABLE public.service_milestones ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS service_milestones_parties ON public.service_milestones;
CREATE POLICY service_milestones_parties
  ON public.service_milestones FOR ALL TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.service_bookings b
      WHERE b.id = booking_id
        AND (b.customer_id = auth.uid() OR b.provider_id = auth.uid())
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.service_bookings b
      WHERE b.id = booking_id
        AND (b.customer_id = auth.uid() OR b.provider_id = auth.uid())
    )
  );

CREATE TABLE IF NOT EXISTS public.service_invoices (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id bigint NOT NULL REFERENCES public.service_bookings(id) ON DELETE CASCADE,
  customer_id uuid NOT NULL,
  provider_id uuid NOT NULL,
  currency text NOT NULL,
  customer_total_cents integer NOT NULL CHECK (customer_total_cents >= 0),
  provider_commission_bps integer NOT NULL DEFAULT 1000 CHECK (provider_commission_bps = 1000),
  provider_commission_cents integer NOT NULL CHECK (provider_commission_cents >= 0),
  provider_settlement_cents integer NOT NULL CHECK (provider_settlement_cents >= 0),
  status text NOT NULL DEFAULT 'issued',
  payment_method text NOT NULL DEFAULT 'unset',
  collection_state text NOT NULL DEFAULT 'uncollected',
  note text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT service_invoices_status_check CHECK (
    status = ANY (ARRAY['draft'::text, 'issued'::text, 'paid'::text, 'void'::text, 'refunded'::text])
  ),
  CONSTRAINT service_invoices_collection_check CHECK (
    collection_state = ANY (ARRAY['uncollected'::text, 'collected_stripe'::text, 'collected_cash'::text, 'void'::text])
  )
);

ALTER TABLE public.service_invoices ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS service_invoices_parties ON public.service_invoices;
CREATE POLICY service_invoices_parties
  ON public.service_invoices FOR SELECT TO authenticated
  USING (customer_id = auth.uid() OR provider_id = auth.uid());

DROP POLICY IF EXISTS service_invoices_insert_parties ON public.service_invoices;
CREATE POLICY service_invoices_insert_parties
  ON public.service_invoices FOR INSERT TO authenticated
  WITH CHECK (customer_id = auth.uid() OR provider_id = auth.uid());

