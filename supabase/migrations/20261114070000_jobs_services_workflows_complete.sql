-- Private resume storage bucket metadata (policies applied when bucket exists)
INSERT INTO storage.buckets (id, name, public)
VALUES ('job-resumes', 'job-resumes', false)
ON CONFLICT (id) DO NOTHING;

-- Applicants may upload/read/delete only under their own user-id folder.
DROP POLICY IF EXISTS job_resumes_applicant_insert ON storage.objects;
CREATE POLICY job_resumes_applicant_insert
  ON storage.objects FOR INSERT TO authenticated
  WITH CHECK (
    bucket_id = 'job-resumes'
    AND (storage.foldername(name))[1] = auth.uid()::text
  );

DROP POLICY IF EXISTS job_resumes_applicant_select ON storage.objects;
CREATE POLICY job_resumes_applicant_select
  ON storage.objects FOR SELECT TO authenticated
  USING (
    bucket_id = 'job-resumes'
    AND (
      (storage.foldername(name))[1] = auth.uid()::text
      OR EXISTS (
        SELECT 1
        FROM public.job_applications a
        JOIN public.jobs j ON j.id = a.job_id
        WHERE a.resume_path = name
          AND j.user_id = auth.uid()
      )
    )
  );

DROP POLICY IF EXISTS job_resumes_applicant_delete ON storage.objects;
CREATE POLICY job_resumes_applicant_delete
  ON storage.objects FOR DELETE TO authenticated
  USING (
    bucket_id = 'job-resumes'
    AND (storage.foldername(name))[1] = auth.uid()::text
  );

CREATE SCHEMA IF NOT EXISTS havkar_private;

CREATE OR REPLACE FUNCTION havkar_private.notify_job_application_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  employer uuid;
  recipient uuid;
  title_text text;
  message_text text;
BEGIN
  SELECT j.user_id INTO employer
  FROM public.jobs j
  WHERE j.id = NEW.job_id;

  IF TG_OP = 'INSERT' THEN
    recipient := employer;
    title_text := 'New job application';
    message_text := 'A candidate applied to job ' || NEW.job_id::text || '.';
  ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
    IF NEW.status = 'withdrawn' THEN
      recipient := employer;
      title_text := 'Application withdrawn';
      message_text := 'An application for job ' || NEW.job_id::text || ' was withdrawn.';
    ELSE
      recipient := NEW.applicant_id;
      title_text := 'Application update';
      message_text := 'Your application for job ' || NEW.job_id::text || ' is now ' || NEW.status || '.';
    END IF;
  ELSE
    RETURN NEW;
  END IF;

  IF recipient IS NULL THEN
    RETURN NEW;
  END IF;

  INSERT INTO public.notifications (user_id, type, title, message, action_url, reference_id)
  VALUES (
    recipient,
    'job',
    title_text,
    message_text,
    'jobs.html',
    NEW.id::text
  );

  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION havkar_private.notify_job_application_change() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS job_applications_notify ON public.job_applications;
CREATE TRIGGER job_applications_notify
  AFTER INSERT OR UPDATE OF status ON public.job_applications
  FOR EACH ROW
  EXECUTE FUNCTION havkar_private.notify_job_application_change();
