-- Service commission ledger.
-- This file is not applied to production by the repository itself.
--
-- The customer is charged the agreed service price.
-- The provider owes 10 percent (1000 basis points).
-- Processing fees and taxes stay at zero until a separate
-- verified assessment exists.
-- collection_state cannot leave 'uncollected'. A row in this
-- ledger is not a collected payment.

CREATE SCHEMA IF NOT EXISTS havkar_private;

GRANT USAGE ON SCHEMA havkar_private TO authenticated, service_role;

ALTER TABLE public.service_bookings
  ADD COLUMN IF NOT EXISTS currency text,
  ADD COLUMN IF NOT EXISTS agreed_price numeric,
  ADD COLUMN IF NOT EXISTS payment_method text DEFAULT 'unset',
  ADD COLUMN IF NOT EXISTS commission_bps integer,
  ADD COLUMN IF NOT EXISTS commission_amount numeric,
  ADD COLUMN IF NOT EXISTS completion_confirmed_at timestamptz,
  ADD COLUMN IF NOT EXISTS cash_payment_acknowledged_at timestamptz,
  ADD COLUMN IF NOT EXISTS terms text;

UPDATE public.service_bookings
SET payment_method = 'unset'
WHERE payment_method IS NULL;

ALTER TABLE public.service_bookings
  ALTER COLUMN payment_method SET DEFAULT 'unset';

ALTER TABLE public.service_bookings
  ALTER COLUMN payment_method SET NOT NULL;

ALTER TABLE public.service_bookings
  DROP CONSTRAINT IF EXISTS service_bookings_payment_method_check;

ALTER TABLE public.service_bookings
  ADD CONSTRAINT service_bookings_payment_method_check
  CHECK (payment_method IN ('unset', 'online', 'cash'));

ALTER TABLE public.service_bookings
  DROP CONSTRAINT IF EXISTS service_bookings_commission_bps_check;

ALTER TABLE public.service_bookings
  ADD CONSTRAINT service_bookings_commission_bps_check
  CHECK (commission_bps IS NULL OR commission_bps = 1000);

ALTER TABLE public.service_bookings
  DROP CONSTRAINT IF EXISTS service_booking_status_check;

ALTER TABLE public.service_bookings
  ADD CONSTRAINT service_booking_status_check
  CHECK (
    status IN (
      'pending',
      'price_proposed',
      'accepted',
      'declined',
      'cancelled',
      'completion_requested',
      'completed',
      'in_review'
    )
  );

CREATE TABLE IF NOT EXISTS public.service_commission_entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id bigint NOT NULL UNIQUE REFERENCES public.service_bookings (id) ON DELETE RESTRICT,
  agreed_amount_cents integer NOT NULL,
  currency text NOT NULL,
  customer_charge_cents integer NOT NULL,
  commission_bps integer NOT NULL,
  commission_cents integer NOT NULL,
  provider_settlement_cents integer NOT NULL,
  payer text NOT NULL,
  stripe_event_id text UNIQUE,
  settlement_channel text NOT NULL DEFAULT 'manual',
  liability_state text NOT NULL DEFAULT 'recorded',
  collection_state text NOT NULL DEFAULT 'uncollected',
  processing_fee_cents integer NOT NULL DEFAULT 0,
  tax_cents integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.service_commission_entries
  ADD COLUMN IF NOT EXISTS settlement_channel text DEFAULT 'manual',
  ADD COLUMN IF NOT EXISTS liability_state text DEFAULT 'recorded',
  ADD COLUMN IF NOT EXISTS collection_state text DEFAULT 'uncollected',
  ADD COLUMN IF NOT EXISTS processing_fee_cents integer DEFAULT 0,
  ADD COLUMN IF NOT EXISTS tax_cents integer DEFAULT 0;

UPDATE public.service_commission_entries
SET
  settlement_channel = COALESCE(settlement_channel, 'manual'),
  liability_state = COALESCE(liability_state, 'recorded'),
  collection_state = 'uncollected',
  processing_fee_cents = 0,
  tax_cents = 0;

ALTER TABLE public.service_commission_entries
  ALTER COLUMN settlement_channel SET DEFAULT 'manual',
  ALTER COLUMN settlement_channel SET NOT NULL,
  ALTER COLUMN liability_state SET DEFAULT 'recorded',
  ALTER COLUMN liability_state SET NOT NULL,
  ALTER COLUMN collection_state SET DEFAULT 'uncollected',
  ALTER COLUMN collection_state SET NOT NULL,
  ALTER COLUMN processing_fee_cents SET DEFAULT 0,
  ALTER COLUMN processing_fee_cents SET NOT NULL,
  ALTER COLUMN tax_cents SET DEFAULT 0,
  ALTER COLUMN tax_cents SET NOT NULL;

ALTER TABLE public.service_commission_entries
  DROP CONSTRAINT IF EXISTS service_commission_entries_amount_check;

ALTER TABLE public.service_commission_entries
  ADD CONSTRAINT service_commission_entries_amount_check
  CHECK (agreed_amount_cents >= 0);

ALTER TABLE public.service_commission_entries
  DROP CONSTRAINT IF EXISTS service_commission_entries_bps_check;

ALTER TABLE public.service_commission_entries
  ADD CONSTRAINT service_commission_entries_bps_check
  CHECK (commission_bps = 1000);

ALTER TABLE public.service_commission_entries
  DROP CONSTRAINT IF EXISTS service_commission_entries_customer_check;

ALTER TABLE public.service_commission_entries
  ADD CONSTRAINT service_commission_entries_customer_check
  CHECK (customer_charge_cents = agreed_amount_cents);

ALTER TABLE public.service_commission_entries
  DROP CONSTRAINT IF EXISTS service_commission_entries_payer_check;

ALTER TABLE public.service_commission_entries
  ADD CONSTRAINT service_commission_entries_payer_check
  CHECK (payer = 'provider');

ALTER TABLE public.service_commission_entries
  DROP CONSTRAINT IF EXISTS service_commission_entries_split_check;

ALTER TABLE public.service_commission_entries
  ADD CONSTRAINT service_commission_entries_split_check
  CHECK (
    commission_cents >= 0
    AND provider_settlement_cents >= 0
    AND commission_cents + provider_settlement_cents = agreed_amount_cents
  );

ALTER TABLE public.service_commission_entries
  DROP CONSTRAINT IF EXISTS service_commission_entries_channel_check;

ALTER TABLE public.service_commission_entries
  ADD CONSTRAINT service_commission_entries_channel_check
  CHECK (settlement_channel IN ('online', 'cash', 'manual'));

ALTER TABLE public.service_commission_entries
  DROP CONSTRAINT IF EXISTS service_commission_entries_liability_check;

ALTER TABLE public.service_commission_entries
  ADD CONSTRAINT service_commission_entries_liability_check
  CHECK (liability_state IN ('recorded', 'owed', 'void'));

ALTER TABLE public.service_commission_entries
  DROP CONSTRAINT IF EXISTS service_commission_entries_collection_check;

ALTER TABLE public.service_commission_entries
  ADD CONSTRAINT service_commission_entries_collection_check
  CHECK (collection_state = 'uncollected');

ALTER TABLE public.service_commission_entries
  DROP CONSTRAINT IF EXISTS service_commission_entries_fee_check;

ALTER TABLE public.service_commission_entries
  ADD CONSTRAINT service_commission_entries_fee_check
  CHECK (processing_fee_cents = 0);

ALTER TABLE public.service_commission_entries
  DROP CONSTRAINT IF EXISTS service_commission_entries_tax_check;

ALTER TABLE public.service_commission_entries
  ADD CONSTRAINT service_commission_entries_tax_check
  CHECK (tax_cents = 0);

CREATE OR REPLACE FUNCTION havkar_private.caller_is_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT COALESCE(auth.jwt() -> 'app_metadata' ->> 'role', '') = 'admin';
$$;

