CREATE OR REPLACE FUNCTION havkar_private.enforce_service_commission_entry()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF NEW.booking_id IS DISTINCT FROM OLD.booking_id
       OR NEW.agreed_amount_cents IS DISTINCT FROM OLD.agreed_amount_cents
       OR NEW.currency IS DISTINCT FROM OLD.currency
       OR NEW.customer_charge_cents IS DISTINCT FROM OLD.customer_charge_cents
       OR NEW.commission_bps IS DISTINCT FROM OLD.commission_bps
       OR NEW.commission_cents IS DISTINCT FROM OLD.commission_cents
       OR NEW.provider_settlement_cents IS DISTINCT FROM OLD.provider_settlement_cents
       OR NEW.payer IS DISTINCT FROM OLD.payer
       OR NEW.settlement_channel IS DISTINCT FROM OLD.settlement_channel
       OR NEW.stripe_event_id IS DISTINCT FROM OLD.stripe_event_id
       OR NEW.processing_fee_cents IS DISTINCT FROM 0
       OR NEW.tax_cents IS DISTINCT FROM 0
       OR NEW.collection_state IS DISTINCT FROM 'uncollected' THEN
      RAISE EXCEPTION 'commission amounts are locked'
        USING ERRCODE = '42501';
    END IF;

    IF NEW.liability_state NOT IN ('recorded', 'owed', 'void') THEN
      RAISE EXCEPTION 'commission liability state is not available'
        USING ERRCODE = '42501';
    END IF;

    NEW.collection_state := 'uncollected';
    NEW.processing_fee_cents := 0;
    NEW.tax_cents := 0;
    RETURN NEW;
  END IF;

  NEW.commission_bps := 1000;
  NEW.payer := 'provider';
  NEW.customer_charge_cents := NEW.agreed_amount_cents;
  NEW.commission_cents := round(NEW.agreed_amount_cents * 1000 / 10000.0)::integer;
  NEW.provider_settlement_cents := NEW.agreed_amount_cents - NEW.commission_cents;
  NEW.processing_fee_cents := 0;
  NEW.tax_cents := 0;
  NEW.collection_state := 'uncollected';

  IF NEW.liability_state IS NULL
     OR NEW.liability_state NOT IN ('recorded', 'owed', 'void') THEN
    NEW.liability_state := 'recorded';
  END IF;

  IF NEW.settlement_channel IS NULL
     OR NEW.settlement_channel NOT IN ('online', 'cash', 'manual') THEN
    NEW.settlement_channel := 'manual';
  END IF;

  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION havkar_private.enforce_service_commission_entry() FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION havkar_private.enforce_service_booking_write()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  service_provider uuid;
  service_price numeric;
  service_currency text;
BEGIN
  IF current_user NOT IN ('anon', 'authenticated') THEN
    IF TG_OP = 'UPDATE'
       AND NEW.payment_method = 'cash'
       AND NEW.status IS DISTINCT FROM 'pending'
       AND NEW.status IS DISTINCT FROM 'cancelled'
       AND NEW.status IS DISTINCT FROM 'declined' THEN
      RAISE EXCEPTION 'cash bookings are not activated'
        USING ERRCODE = '42501';
    END IF;
    RETURN NEW;
  END IF;

  IF TG_OP = 'INSERT' THEN
    SELECT provider_id, price, currency
      INTO service_provider, service_price, service_currency
    FROM public.services
    WHERE id = NEW.service_id
      AND status = 'active';

    IF service_provider IS NULL OR NEW.provider_id IS DISTINCT FROM service_provider THEN
      RAISE EXCEPTION 'booking provider does not match the service provider'
        USING ERRCODE = '42501';
    END IF;

    IF NEW.customer_id IS DISTINCT FROM auth.uid()
       OR NEW.status IS DISTINCT FROM 'pending'
       OR NEW.commission_bps IS NOT NULL
       OR NEW.commission_amount IS NOT NULL
       OR NEW.completion_confirmed_at IS NOT NULL
       OR NEW.cash_payment_acknowledged_at IS NOT NULL THEN
      RAISE EXCEPTION 'booking insert is outside the allowed request'
        USING ERRCODE = '42501';
    END IF;

    IF NEW.payment_method IS NULL THEN
      NEW.payment_method := 'unset';
    END IF;

    IF NEW.payment_method NOT IN ('unset', 'online', 'cash') THEN
      RAISE EXCEPTION 'booking insert is outside the allowed request'
        USING ERRCODE = '42501';
    END IF;

    IF NEW.agreed_price IS NOT NULL AND NEW.agreed_price IS DISTINCT FROM service_price THEN
      RAISE EXCEPTION 'booking price is taken from the service'
        USING ERRCODE = '42501';
    END IF;

    IF NEW.currency IS NOT NULL
       AND lower(btrim(NEW.currency)) IS DISTINCT FROM lower(btrim(COALESCE(service_currency, ''))) THEN
      RAISE EXCEPTION 'booking currency is taken from the service'
        USING ERRCODE = '42501';
    END IF;

    NEW.agreed_price := service_price;
    NEW.currency := service_currency;
  END IF;

  IF TG_OP = 'UPDATE' THEN
    IF NEW.id IS DISTINCT FROM OLD.id
       OR NEW.service_id IS DISTINCT FROM OLD.service_id
       OR NEW.customer_id IS DISTINCT FROM OLD.customer_id
       OR NEW.provider_id IS DISTINCT FROM OLD.provider_id
       OR NEW.created_at IS DISTINCT FROM OLD.created_at
       OR NEW.booking_date IS DISTINCT FROM OLD.booking_date
       OR NEW.booking_time IS DISTINCT FROM OLD.booking_time
       OR NEW.message IS DISTINCT FROM OLD.message
       OR NEW.payment_method IS DISTINCT FROM OLD.payment_method
       OR NEW.terms IS DISTINCT FROM OLD.terms
       OR NEW.commission_bps IS DISTINCT FROM OLD.commission_bps
       OR NEW.commission_amount IS DISTINCT FROM OLD.commission_amount
       OR NEW.agreed_price IS DISTINCT FROM OLD.agreed_price
       OR NEW.currency IS DISTINCT FROM OLD.currency
       OR NEW.completion_confirmed_at IS DISTINCT FROM OLD.completion_confirmed_at
       OR NEW.cash_payment_acknowledged_at IS DISTINCT FROM OLD.cash_payment_acknowledged_at THEN
      RAISE EXCEPTION 'booking identity and settlement fields are locked'
        USING ERRCODE = '42501';
    END IF;

    IF (NEW.payment_method = 'cash' OR OLD.payment_method = 'cash')
       AND NEW.status IS DISTINCT FROM OLD.status
       AND NEW.status NOT IN ('cancelled', 'declined') THEN
      RAISE EXCEPTION 'cash bookings are not activated'
        USING ERRCODE = '42501';
    END IF;

    IF NEW.status IS DISTINCT FROM OLD.status THEN
      IF auth.uid() = OLD.provider_id THEN
        IF NOT (
          (OLD.status = 'pending' AND NEW.status IN ('accepted', 'declined', 'price_proposed'))
          OR (OLD.status = 'price_proposed' AND NEW.status IN ('accepted', 'declined'))
        ) THEN
          RAISE EXCEPTION 'provider booking transition is not allowed'
            USING ERRCODE = '42501';
        END IF;
        IF NEW.status IN ('accepted', 'completion_requested')
           AND OLD.payment_method IS DISTINCT FROM 'online'
           AND NEW.payment_method IS DISTINCT FROM 'online' THEN
          RAISE EXCEPTION 'provider acceptance requires an online payment method'
            USING ERRCODE = '42501';
        END IF;
      ELSIF auth.uid() = OLD.customer_id THEN
        IF NOT (
          NEW.status = 'cancelled'
          AND OLD.status IN ('pending', 'price_proposed', 'accepted')
        ) THEN
          RAISE EXCEPTION 'customer booking transition is not allowed'
            USING ERRCODE = '42501';
        END IF;
      ELSE
        RAISE EXCEPTION 'booking update is not allowed'
          USING ERRCODE = '42501';
      END IF;
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION havkar_private.enforce_service_booking_write() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION havkar_private.enforce_service_booking_write() TO authenticated;

DROP TRIGGER IF EXISTS service_bookings_enforce_write ON public.service_bookings;

CREATE TRIGGER service_bookings_enforce_write
  BEFORE INSERT OR UPDATE ON public.service_bookings
  FOR EACH ROW EXECUTE FUNCTION havkar_private.enforce_service_booking_write();

CREATE OR REPLACE FUNCTION havkar_private.record_service_commission_liability()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  cents integer;
  channel text;
  liability text;
BEGIN
  IF NEW.agreed_price IS NULL OR NEW.currency IS NULL THEN
    RETURN NEW;
  END IF;

  IF NEW.agreed_price < 0 OR NEW.agreed_price > 1000000 THEN
    RAISE EXCEPTION 'service price cannot be commissioned'
      USING ERRCODE = '42501';
  END IF;

  cents := round(NEW.agreed_price * 100)::integer;

  IF cents < 0 OR cents > 100000000 THEN
    RAISE EXCEPTION 'service price cannot be commissioned'
      USING ERRCODE = '42501';
  END IF;

  channel := CASE NEW.payment_method
    WHEN 'cash' THEN 'cash'
    WHEN 'online' THEN 'online'
    ELSE 'manual'
  END;

  liability := CASE
    WHEN NEW.status IN ('cancelled', 'declined') THEN 'void'
    WHEN NEW.status = 'completed' THEN 'owed'
    ELSE 'recorded'
  END;

  INSERT INTO public.service_commission_entries (
    booking_id,
    agreed_amount_cents,
    currency,
    customer_charge_cents,
    commission_bps,
    commission_cents,
    provider_settlement_cents,
    payer,
    settlement_channel,
    liability_state,
    collection_state,
    processing_fee_cents,
    tax_cents
  ) VALUES (
    NEW.id,
    cents,
    NEW.currency,
    cents,
    1000,
    0,
    0,
    'provider',
    channel,
    liability,
    'uncollected',
    0,
    0
  )
  ON CONFLICT (booking_id) DO UPDATE
  SET liability_state = EXCLUDED.liability_state;

  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION havkar_private.record_service_commission_liability() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION havkar_private.record_service_commission_liability() TO authenticated, service_role;

DROP TRIGGER IF EXISTS service_bookings_record_commission ON public.service_bookings;

CREATE TRIGGER service_bookings_record_commission
  AFTER INSERT OR UPDATE OF status, payment_method, agreed_price
  ON public.service_bookings
  FOR EACH ROW EXECUTE FUNCTION havkar_private.record_service_commission_liability();

DROP TRIGGER IF EXISTS service_commission_entries_force_split ON public.service_commission_entries;

CREATE TRIGGER service_commission_entries_force_split
  BEFORE INSERT OR UPDATE ON public.service_commission_entries
  FOR EACH ROW EXECUTE FUNCTION havkar_private.enforce_service_commission_entry();

ALTER TABLE public.service_commission_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.service_commission_entries FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS service_commission_entries_party_select ON public.service_commission_entries;

CREATE POLICY service_commission_entries_party_select
  ON public.service_commission_entries
  FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.service_bookings booking
      WHERE booking.id = service_commission_entries.booking_id
        AND (
          booking.customer_id = (SELECT auth.uid())
          OR booking.provider_id = (SELECT auth.uid())
        )
    )
    OR havkar_private.caller_is_admin()
  );

