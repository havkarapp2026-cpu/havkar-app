CREATE OR REPLACE FUNCTION public.havkar_public_verification_badges(p_user_id uuid)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT COALESCE(jsonb_agg(jsonb_build_object(
    'badge_type', c.badge_type,
    'status', c.status,
    'expires_at', c.expires_at,
    'reviewed_at', c.reviewed_at
  ) ORDER BY c.badge_type), '[]'::jsonb)
  FROM public.havkar_verification_cases c
  WHERE c.user_id = p_user_id
    AND c.status = 'approved'
    AND (c.expires_at IS NULL OR c.expires_at > now());
$$;

CREATE OR REPLACE FUNCTION public.havkar_review_verification_case(
  p_case_id bigint,
  p_decision text,
  p_notes text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  role_name text := public.havkar_session_role();
  current uuid := (SELECT auth.uid());
  row public.havkar_verification_cases%ROWTYPE;
  next_status text;
BEGIN
  IF role_name IS NULL OR role_name NOT IN ('owner','admin','staff') THEN
    RAISE EXCEPTION 'not authorized' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO row FROM public.havkar_verification_cases WHERE id = p_case_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'verification case not found' USING ERRCODE = 'P0002';
  END IF;

  next_status := lower(btrim(p_decision));
  IF next_status NOT IN ('approved','rejected','suspended','revoked','needs_more_info') THEN
    RAISE EXCEPTION 'invalid decision' USING ERRCODE = '23514';
  END IF;

  -- Payment cannot auto-approve: reviewers must call this RPC explicitly.
  UPDATE public.havkar_verification_cases
  SET status = next_status,
      reviewed_by = current,
      reviewed_at = now(),
      updated_at = now(),
      rejection_reason = CASE
        WHEN next_status IN ('rejected','suspended','revoked') THEN COALESCE(p_notes, rejection_reason)
        ELSE rejection_reason
      END,
      evidence_notes = CASE
        WHEN p_notes IS NULL OR btrim(p_notes) = '' THEN evidence_notes
        ELSE evidence_notes || E'\n' || p_notes
      END
  WHERE id = p_case_id
  RETURNING * INTO row;

  INSERT INTO public.havkar_verification_audit (
    case_id, actor_user_id, action, from_status, to_status, detail
  ) VALUES (
    p_case_id, current, 'review', NULL, next_status,
    jsonb_build_object('notes', p_notes, 'paid_auto_award', false)
  );

  RETURN jsonb_build_object(
    'ok', true,
    'case_id', row.id,
    'user_id', row.user_id,
    'badge_type', row.badge_type,
    'status', row.status,
    'app_metadata_sync_required', next_status = 'approved'
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.havkar_owner_finance_accounting_summary(
  p_from timestamptz DEFAULT NULL,
  p_to timestamptz DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  from_ts timestamptz := COALESCE(p_from, '1970-01-01'::timestamptz);
  to_ts timestamptz := COALESCE(p_to, now() + interval '1 day');
BEGIN
  IF NOT havkar_private.caller_is_owner() THEN
    RAISE EXCEPTION 'not authorized' USING ERRCODE = '42501';
  END IF;

  RETURN jsonb_build_object(
    'generated_at', now(),
    'window', jsonb_build_object('from', from_ts, 'to', to_ts),
    'journal_entries', (
      SELECT count(*)::int FROM public.havkar_finance_journal_entries
      WHERE occurred_at >= from_ts AND occurred_at < to_ts
    ),
    'documents', (
      SELECT jsonb_build_object(
        'receipts', count(*) FILTER (WHERE document_kind = 'payment_receipt'),
        'tax_invoices', count(*) FILTER (WHERE document_kind = 'tax_invoice'),
        'credit_notes', count(*) FILTER (WHERE document_kind = 'credit_note')
      )
      FROM public.havkar_finance_documents
      WHERE issue_date >= from_ts::date AND issue_date <= to_ts::date
    ),
    'revenue_credits_cents', (
      SELECT COALESCE(SUM(l.credit_cents),0)::bigint
      FROM public.havkar_finance_journal_lines l
      JOIN public.havkar_finance_journal_entries e ON e.id = l.entry_id
      JOIN public.havkar_finance_accounts a ON a.code = l.account_code
      WHERE a.account_type = 'revenue'
        AND e.occurred_at >= from_ts AND e.occurred_at < to_ts
    ),
    'expense_debits_cents', (
      SELECT COALESCE(SUM(l.debit_cents),0)::bigint
      FROM public.havkar_finance_journal_lines l
      JOIN public.havkar_finance_journal_entries e ON e.id = l.entry_id
      JOIN public.havkar_finance_accounts a ON a.code = l.account_code
      WHERE a.account_type = 'expense'
        AND e.occurred_at >= from_ts AND e.occurred_at < to_ts
    ),
    'seller_payables_credit_cents', (
      SELECT COALESCE(SUM(l.credit_cents),0)::bigint
      FROM public.havkar_finance_journal_lines l
      JOIN public.havkar_finance_journal_entries e ON e.id = l.entry_id
      WHERE l.account_code = '2000'
        AND e.occurred_at >= from_ts AND e.occurred_at < to_ts
    ),
    'issuance_gates', (
      SELECT to_jsonb(g) FROM public.havkar_finance_issuance_gates g WHERE g.id = true
    ),
    'stripe_webhook_events_live', (
      SELECT count(*)::int FROM public.stripe_webhook_events WHERE livemode = true
    ),
    'fees', jsonb_build_object(
      'buy_sell_buyer_bps', 200,
      'buy_sell_seller_bps', 300,
      'services_provider_bps', 1000,
      'personal_listing_publication_fee_cents', 0
    )
  );
END;
$$;

