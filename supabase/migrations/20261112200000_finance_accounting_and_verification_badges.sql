CREATE TABLE IF NOT EXISTS public.havkar_finance_journal_entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entry_ref text NOT NULL UNIQUE,
  source_system text NOT NULL
    CHECK (source_system = ANY (ARRAY[
      'stripe_live','stripe_connect','stellar_mainnet','stellar_testnet',
      'manual_owner','system'
    ])),
  source_event_id text,
  source_object_id text,
  occurred_at timestamptz NOT NULL,
  posted_at timestamptz NOT NULL DEFAULT now(),
  currency text NOT NULL DEFAULT 'EUR',
  memo text NOT NULL DEFAULT '',
  reconciliation_status text NOT NULL DEFAULT 'unreconciled'
    CHECK (reconciliation_status = ANY (ARRAY[
      'unreconciled','matched','exception','waived'
    ])),
  livemode boolean NOT NULL DEFAULT true,
  created_by uuid REFERENCES auth.users (id),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT havkar_finance_journal_source_unique
    UNIQUE NULLS NOT DISTINCT (source_system, source_event_id)
);

CREATE TABLE IF NOT EXISTS public.havkar_finance_journal_lines (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entry_id bigint NOT NULL REFERENCES public.havkar_finance_journal_entries (id) ON DELETE RESTRICT,
  account_code text NOT NULL REFERENCES public.havkar_finance_accounts (code),
  debit_cents bigint NOT NULL DEFAULT 0 CHECK (debit_cents >= 0),
  credit_cents bigint NOT NULL DEFAULT 0 CHECK (credit_cents >= 0),
  party_user_id uuid,
  party_role text
    CHECK (party_role IS NULL OR party_role = ANY (ARRAY[
      'buyer','seller','provider','platform','stripe','customer'
    ])),
  description text NOT NULL DEFAULT '',
  CONSTRAINT havkar_finance_line_one_side CHECK (
    (debit_cents > 0 AND credit_cents = 0) OR
    (credit_cents > 0 AND debit_cents = 0)
  )
);

CREATE INDEX IF NOT EXISTS havkar_finance_journal_occurred_idx
  ON public.havkar_finance_journal_entries (occurred_at DESC);
CREATE INDEX IF NOT EXISTS havkar_finance_journal_object_idx
  ON public.havkar_finance_journal_entries (source_object_id);
CREATE INDEX IF NOT EXISTS havkar_finance_lines_entry_idx
  ON public.havkar_finance_journal_lines (entry_id);

CREATE OR REPLACE FUNCTION public.havkar_finance_assert_balanced()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  debits bigint;
  credits bigint;
BEGIN
  SELECT COALESCE(SUM(debit_cents),0), COALESCE(SUM(credit_cents),0)
    INTO debits, credits
  FROM public.havkar_finance_journal_lines
  WHERE entry_id = NEW.entry_id;

  IF debits <> credits THEN
    RAISE EXCEPTION 'journal entry % is not balanced (debit=% credit=%)',
      NEW.entry_id, debits, credits
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_havkar_finance_line_balance ON public.havkar_finance_journal_lines;
CREATE CONSTRAINT TRIGGER trg_havkar_finance_line_balance
AFTER INSERT OR UPDATE OR DELETE ON public.havkar_finance_journal_lines
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION public.havkar_finance_assert_balanced();

