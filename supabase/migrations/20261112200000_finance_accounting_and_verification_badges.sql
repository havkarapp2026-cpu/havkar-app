CREATE TABLE IF NOT EXISTS public.havkar_verification_cases (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  badge_type text NOT NULL
    CHECK (badge_type = ANY (ARRAY['personal','business','company'])),
  status text NOT NULL DEFAULT 'pending'
    CHECK (status = ANY (ARRAY[
      'pending','needs_more_info','approved','rejected','suspended','revoked','expired'
    ])),
  evidence_notes text NOT NULL DEFAULT '',
  evidence_paths jsonb NOT NULL DEFAULT '[]'::jsonb,
  business_application_id bigint REFERENCES public.business_applications (id),
  reviewed_by uuid REFERENCES auth.users (id),
