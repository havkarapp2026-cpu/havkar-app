-- Business verification documents + independent review workflow.
-- Does not invent VAT/address values. Does not enable payments.
-- Self-approval of one's own business application is refused.

-- 1) Allow review lifecycle statuses on applications.
ALTER TABLE public.business_applications
  DROP CONSTRAINT IF EXISTS business_applications_status_check;

ALTER TABLE public.business_applications
  ADD CONSTRAINT business_applications_status_check
  CHECK (
    lower(COALESCE(status, '')) IN (
      'pending',
      'under_review',
      'needs_more_info',
      'approved',
      'rejected'
    )
  );

-- 2) Private evidence documents (separate from applicant-locked documents jsonb).
CREATE TABLE IF NOT EXISTS public.business_application_documents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id bigint NOT NULL REFERENCES public.business_applications (id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  doc_type text NOT NULL CHECK (
    doc_type IN (
      'vat_registration',
      'company_registration',
      'proof_of_registered_address',
      'other_supporting'
    )
  ),
  storage_path text NOT NULL,
  mime_type text NOT NULL CHECK (
    mime_type IN (
      'application/pdf',
      'image/jpeg',
      'image/png',
      'image/webp'
    )
  ),
  byte_size integer NOT NULL CHECK (byte_size > 0 AND byte_size <= 10485760),
  original_filename text,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  CONSTRAINT business_application_documents_path_unique UNIQUE (storage_path)
);

CREATE INDEX IF NOT EXISTS business_application_documents_app_idx
  ON public.business_application_documents (application_id, doc_type);

ALTER TABLE public.business_application_documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.business_application_documents FORCE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.business_application_documents FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON TABLE public.business_application_documents TO authenticated;
GRANT ALL ON TABLE public.business_application_documents TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.business_application_documents_id_seq TO authenticated, service_role;

DROP POLICY IF EXISTS business_docs_select_own ON public.business_application_documents;
CREATE POLICY business_docs_select_own
ON public.business_application_documents
FOR SELECT
TO authenticated
USING (
  user_id = (SELECT auth.uid())
  OR COALESCE(havkar_private.caller_is_admin(), false)
);

DROP POLICY IF EXISTS business_docs_insert_own ON public.business_application_documents;
CREATE POLICY business_docs_insert_own
ON public.business_application_documents
FOR INSERT
TO authenticated
WITH CHECK (
  user_id = (SELECT auth.uid())
  AND EXISTS (
    SELECT 1
    FROM public.business_applications ba
    WHERE ba.id = application_id
      AND ba.user_id = (SELECT auth.uid())
      AND lower(COALESCE(ba.status, '')) IN ('pending', 'needs_more_info', 'under_review')
  )
);

-- 3) Review audit trail.
CREATE TABLE IF NOT EXISTS public.business_application_review_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id bigint NOT NULL REFERENCES public.business_applications (id) ON DELETE CASCADE,
  actor_id uuid,
  decision text NOT NULL CHECK (
    decision IN ('approve', 'reject', 'request_more_info', 'mark_under_review')
  ),
  notes text,
  evidence_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now())
);

CREATE INDEX IF NOT EXISTS business_application_review_events_app_idx
  ON public.business_application_review_events (application_id, created_at DESC);

ALTER TABLE public.business_application_review_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.business_application_review_events FORCE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.business_application_review_events FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.business_application_review_events TO authenticated;
GRANT ALL ON TABLE public.business_application_review_events TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.business_application_review_events_id_seq TO authenticated, service_role;

