-- Applicants may keep status pending when updating fields, and may move
-- needs_more_info -> pending after supplying more information.
DROP POLICY IF EXISTS "Users can update own business application" ON public.business_applications;
CREATE POLICY "Users can update own business application"
ON public.business_applications
FOR UPDATE
TO authenticated
USING (
  (SELECT auth.uid()) = user_id
  AND lower(COALESCE(status, '')) IN ('pending', 'needs_more_info')
)
WITH CHECK (
  (SELECT auth.uid()) = user_id
  AND lower(COALESCE(status, '')) IN ('pending', 'needs_more_info')
);

-- 4) Private storage bucket for business evidence.
DO $$
DECLARE
  existing_name text;
  existing_public boolean;
  existing_limit bigint;
  existing_types text[];
  expected_types constant text[] := ARRAY[
    'application/pdf',
    'image/jpeg',
    'image/png',
    'image/webp'
  ];
BEGIN
  SELECT name, public, file_size_limit, allowed_mime_types
    INTO existing_name, existing_public, existing_limit, existing_types
  FROM storage.buckets
  WHERE id = 'business-evidence';

  IF NOT FOUND THEN
    INSERT INTO storage.buckets (
      id, name, public, file_size_limit, allowed_mime_types
    ) VALUES (
      'business-evidence',
      'business-evidence',
      false,
      10485760,
      expected_types
    );
  ELSIF existing_public IS DISTINCT FROM false
     OR existing_limit IS DISTINCT FROM 10485760 THEN
    RAISE EXCEPTION
      'business-evidence bucket exists with incompatible settings'
      USING ERRCODE = '22023';
  END IF;
END $$;

DROP POLICY IF EXISTS business_evidence_storage_insert ON storage.objects;
CREATE POLICY business_evidence_storage_insert
ON storage.objects
FOR INSERT
TO authenticated
WITH CHECK (
  bucket_id = 'business-evidence'
  AND (SELECT auth.uid()) IS NOT NULL
  AND lower((storage.foldername(name))[1]) = lower((SELECT auth.uid())::text)
  AND cardinality(storage.foldername(name)) = 3
  AND (storage.foldername(name))[2] IN (
    'vat_registration',
    'company_registration',
    'proof_of_registered_address',
    'other_supporting'
  )
  AND name !~* '(^|/)identity(/|$)|passport|selfie|id[_-]?card'
);

DROP POLICY IF EXISTS business_evidence_storage_select_own ON storage.objects;
CREATE POLICY business_evidence_storage_select_own
ON storage.objects
FOR SELECT
TO authenticated
USING (
  bucket_id = 'business-evidence'
  AND (SELECT auth.uid()) IS NOT NULL
  AND lower((storage.foldername(name))[1]) = lower((SELECT auth.uid())::text)
);

DROP POLICY IF EXISTS business_evidence_storage_select_admin ON storage.objects;
CREATE POLICY business_evidence_storage_select_admin
ON storage.objects
FOR SELECT
TO authenticated
USING (
  bucket_id = 'business-evidence'
  AND COALESCE(havkar_private.caller_is_admin(), false)
);

-- 5) Missing evidence helper.
CREATE OR REPLACE FUNCTION public.business_application_missing_documents(p_application_id bigint)
RETURNS text[]
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  WITH required(doc_type) AS (
    VALUES
      ('vat_registration'),
      ('company_registration'),
      ('proof_of_registered_address')
  ),
  present AS (
    SELECT DISTINCT d.doc_type
    FROM public.business_application_documents d
    WHERE d.application_id = p_application_id
  )
  SELECT COALESCE(
    array_agg(required.doc_type ORDER BY required.doc_type),
    ARRAY[]::text[]
  )
  FROM required
  LEFT JOIN present ON present.doc_type = required.doc_type
  WHERE present.doc_type IS NULL;
$$;

REVOKE ALL ON FUNCTION public.business_application_missing_documents(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.business_application_missing_documents(bigint) TO authenticated, service_role;

-- 6) Independent review RPC (no self-approval).
CREATE OR REPLACE FUNCTION public.review_business_application(
  p_application_id bigint,
  p_decision text,
  p_notes text DEFAULT NULL
)
RETURNS public.business_applications
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  actor uuid := (SELECT auth.uid());
  app public.business_applications;
  decision text := lower(btrim(COALESCE(p_decision, '')));
  missing text[];
  snapshot jsonb;
  next_status text;
BEGIN
  IF actor IS NULL THEN
    RAISE EXCEPTION 'authentication required' USING ERRCODE = '42501';
  END IF;

  IF NOT COALESCE(havkar_private.caller_is_admin(), false) THEN
    RAISE EXCEPTION 'administrator authorization required' USING ERRCODE = '42501';
  END IF;

  IF decision NOT IN ('approve', 'reject', 'request_more_info', 'mark_under_review') THEN
    RAISE EXCEPTION 'invalid review decision' USING ERRCODE = '23514';
  END IF;

  SELECT * INTO app
  FROM public.business_applications
  WHERE id = p_application_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'business application not found' USING ERRCODE = 'P0002';
  END IF;

  -- Explicit anti-self-approval / anti-self-review.
  IF app.user_id = actor THEN
    RAISE EXCEPTION 'a reviewer cannot decide their own business application'
      USING ERRCODE = '42501';
  END IF;

  IF lower(COALESCE(app.status, '')) = 'approved' THEN
    RAISE EXCEPTION 'approved applications are locked' USING ERRCODE = '42501';
  END IF;

  missing := public.business_application_missing_documents(app.id);

  SELECT COALESCE(jsonb_agg(jsonb_build_object(
    'id', d.id,
    'doc_type', d.doc_type,
    'storage_path', d.storage_path,
    'mime_type', d.mime_type,
    'byte_size', d.byte_size,
    'created_at', d.created_at
  ) ORDER BY d.doc_type, d.id), '[]'::jsonb)
  INTO snapshot
  FROM public.business_application_documents d
  WHERE d.application_id = app.id;

  IF decision = 'approve' THEN
    IF COALESCE(array_length(missing, 1), 0) > 0 THEN
      RAISE EXCEPTION 'required verification documents missing: %', array_to_string(missing, ', ')
        USING ERRCODE = '23514';
    END IF;
    IF NULLIF(btrim(COALESCE(app.vat_number, '')), '') IS NULL THEN
      RAISE EXCEPTION 'vat_number is required before approval' USING ERRCODE = '23514';
    END IF;
    IF NULLIF(btrim(COALESCE(app.address, '')), '') IS NULL THEN
      RAISE EXCEPTION 'registered address is required before approval' USING ERRCODE = '23514';
    END IF;
    IF NULLIF(btrim(COALESCE(app.legal_name, '')), '') IS NULL THEN
      RAISE EXCEPTION 'legal_name is required before approval' USING ERRCODE = '23514';
    END IF;
    next_status := 'approved';
  ELSIF decision = 'reject' THEN
    next_status := 'rejected';
  ELSIF decision = 'request_more_info' THEN
    next_status := 'needs_more_info';
  ELSE
    next_status := 'under_review';
  END IF;

  UPDATE public.business_applications
  SET
    status = next_status,
    reviewed_at = timezone('utc', now()),
    reviewed_by = actor,
    review_notes = NULLIF(btrim(COALESCE(p_notes, '')), ''),
    rejection_reason = CASE
      WHEN decision = 'reject' THEN NULLIF(btrim(COALESCE(p_notes, '')), '')
      ELSE NULL
    END,
    updated_at = timezone('utc', now())
  WHERE id = app.id
  RETURNING * INTO app;

  INSERT INTO public.business_application_review_events (
    application_id, actor_id, decision, notes, evidence_snapshot
  ) VALUES (
    app.id, actor, decision, NULLIF(btrim(COALESCE(p_notes, '')), ''), snapshot
  );

  RETURN app;
END;
$$;

REVOKE ALL ON FUNCTION public.review_business_application(bigint, text, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.review_business_application(bigint, text, text) TO authenticated, service_role;

-- 7) Register a document metadata row after a successful private upload.
CREATE OR REPLACE FUNCTION public.register_business_application_document(
  p_application_id bigint,
  p_doc_type text,
  p_storage_path text,
  p_mime_type text,
  p_byte_size integer,
  p_original_filename text DEFAULT NULL
)
RETURNS public.business_application_documents
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  actor uuid := (SELECT auth.uid());
  app public.business_applications;
  row public.business_application_documents;
  doc_type text := lower(btrim(COALESCE(p_doc_type, '')));
BEGIN
  IF actor IS NULL THEN
    RAISE EXCEPTION 'authentication required' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO app
  FROM public.business_applications
  WHERE id = p_application_id;

  IF NOT FOUND OR app.user_id IS DISTINCT FROM actor THEN
    RAISE EXCEPTION 'business application not found' USING ERRCODE = 'P0002';
  END IF;

  IF lower(COALESCE(app.status, '')) NOT IN ('pending', 'needs_more_info', 'under_review') THEN
    RAISE EXCEPTION 'documents cannot be added in this status' USING ERRCODE = '42501';
  END IF;

  IF doc_type NOT IN (
    'vat_registration',
    'company_registration',
    'proof_of_registered_address',
    'other_supporting'
  ) THEN
    RAISE EXCEPTION 'invalid document type' USING ERRCODE = '23514';
  END IF;

  IF p_storage_path IS NULL
     OR position(actor::text || '/' || doc_type || '/' IN p_storage_path) <> 1 THEN
    RAISE EXCEPTION 'invalid storage path' USING ERRCODE = '42501';
  END IF;

  INSERT INTO public.business_application_documents (
    application_id, user_id, doc_type, storage_path, mime_type, byte_size, original_filename
  ) VALUES (
    app.id,
    actor,
    doc_type,
    p_storage_path,
    p_mime_type,
    p_byte_size,
    NULLIF(btrim(COALESCE(p_original_filename, '')), '')
  )
  RETURNING * INTO row;

  RETURN row;
END;
$$;

REVOKE ALL ON FUNCTION public.register_business_application_document(bigint, text, text, text, integer, text)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.register_business_application_document(bigint, text, text, text, integer, text)
  TO authenticated;

-- 8) Applicant write guard: allow pending/needs_more_info edits and resubmit.
CREATE OR REPLACE FUNCTION public.enforce_business_application_applicant_write()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO 'public'
AS $function$
BEGIN
  IF current_user <> 'authenticated' THEN
    IF TG_OP = 'DELETE' THEN
      RETURN OLD;
    END IF;
    RETURN NEW;
  END IF;

  IF TG_OP = 'DELETE' THEN
    IF lower(COALESCE(OLD.status, '')) = 'approved' THEN
      RAISE EXCEPTION 'applicants cannot delete an approved business application'
        USING ERRCODE = '42501';
    END IF;
    RETURN OLD;
  END IF;

  IF TG_OP = 'INSERT' THEN
    IF NEW.status IS NULL THEN
      NEW.status := 'pending';
    END IF;

    IF NEW.user_id IS DISTINCT FROM auth.uid()
       OR NEW.status IS DISTINCT FROM 'pending'
       OR NEW.reviewed_at IS NOT NULL
       OR NEW.reviewed_by IS NOT NULL
       OR NEW.review_notes IS NOT NULL
       OR NEW.rejection_reason IS NOT NULL THEN
      RAISE EXCEPTION 'business applications must be submitted by the current user as pending without review fields'
        USING ERRCODE = '42501';
    END IF;

    RETURN NEW;
  END IF;

  IF TG_OP = 'UPDATE' THEN
    IF OLD.user_id IS DISTINCT FROM auth.uid()
       OR lower(COALESCE(OLD.status, '')) = 'approved'
       OR NEW.user_id IS DISTINCT FROM OLD.user_id
       OR NEW.id IS DISTINCT FROM OLD.id
       OR NEW.created_at IS DISTINCT FROM OLD.created_at
       OR NEW.reviewed_at IS DISTINCT FROM OLD.reviewed_at
       OR NEW.reviewed_by IS DISTINCT FROM OLD.reviewed_by
       OR NEW.review_notes IS DISTINCT FROM OLD.review_notes
       OR NEW.rejection_reason IS DISTINCT FROM OLD.rejection_reason
       OR NEW.documents IS DISTINCT FROM OLD.documents THEN
      RAISE EXCEPTION 'applicants cannot change business application ownership, review fields, or an approved application'
        USING ERRCODE = '42501';
    END IF;

    IF lower(COALESCE(OLD.status, '')) NOT IN ('pending', 'needs_more_info') THEN
      RAISE EXCEPTION 'applicants cannot edit applications in this status'
        USING ERRCODE = '42501';
    END IF;

    IF lower(COALESCE(NEW.status, '')) NOT IN ('pending', 'needs_more_info') THEN
      RAISE EXCEPTION 'applicants cannot set review-controlled statuses'
        USING ERRCODE = '42501';
    END IF;
  END IF;

  RETURN NEW;
END;
$function$;
