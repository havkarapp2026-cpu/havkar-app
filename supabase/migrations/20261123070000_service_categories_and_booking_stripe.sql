-- Additive Services categories + booking Stripe session reference.
-- Does not delete existing services/bookings data.

CREATE TABLE IF NOT EXISTS public.service_categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE,
  label text NOT NULL,
  parent_slug text,
  sort_order integer NOT NULL DEFAULT 100,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.service_categories ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.service_categories FROM PUBLIC, anon;
GRANT SELECT ON TABLE public.service_categories TO authenticated, anon;
GRANT ALL ON TABLE public.service_categories TO service_role;

DROP POLICY IF EXISTS service_categories_public_select ON public.service_categories;
CREATE POLICY service_categories_public_select
ON public.service_categories
FOR SELECT
TO anon, authenticated
USING (active = true);

