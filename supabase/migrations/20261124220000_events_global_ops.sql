-- HAVKAR Events global ops (additive, non-destructive).
-- Extends events for venue geo, policy, online access, seat labels,
-- and refund *requests* (no automatic Stripe refund execution).

ALTER TABLE public.events
  ADD COLUMN IF NOT EXISTS venue_lat double precision,
  ADD COLUMN IF NOT EXISTS venue_lng double precision,
  ADD COLUMN IF NOT EXISTS timezone text,
  ADD COLUMN IF NOT EXISTS cancellation_policy text,
  ADD COLUMN IF NOT EXISTS age_restriction text,
  ADD COLUMN IF NOT EXISTS accessibility_notes text,
  ADD COLUMN IF NOT EXISTS is_online boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS online_access_url text,
  ADD COLUMN IF NOT EXISTS sales_paused boolean NOT NULL DEFAULT false;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'events_venue_lat_range'
  ) THEN
    ALTER TABLE public.events
      ADD CONSTRAINT events_venue_lat_range
      CHECK (venue_lat IS NULL OR (venue_lat >= -90 AND venue_lat <= 90));
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'events_venue_lng_range'
  ) THEN
    ALTER TABLE public.events
      ADD CONSTRAINT events_venue_lng_range
      CHECK (venue_lng IS NULL OR (venue_lng >= -180 AND venue_lng <= 180));
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.event_seats (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id bigint NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
  seat_label text NOT NULL,
  section text,
  row_label text,
  price_eur numeric(12,2),
  status text NOT NULL DEFAULT 'available',
  held_by uuid,
  hold_expires_at timestamptz,
  ticket_id bigint REFERENCES public.event_tickets(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT event_seats_label_length CHECK (char_length(seat_label) BETWEEN 1 AND 40),
  CONSTRAINT event_seats_status_check CHECK (
    status = ANY (ARRAY['available'::text, 'held'::text, 'sold'::text, 'blocked'::text])
  ),
  CONSTRAINT event_seats_unique_label UNIQUE (event_id, seat_label)
);

CREATE INDEX IF NOT EXISTS event_seats_event_status_idx
  ON public.event_seats (event_id, status);

ALTER TABLE public.event_seats ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "event seats public read available" ON public.event_seats;
CREATE POLICY "event seats public read available"
  ON public.event_seats
  FOR SELECT
  TO anon, authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.events e
      WHERE e.id = event_id
        AND e.is_public = true
        AND e.status = 'active'
    )
    OR EXISTS (
      SELECT 1 FROM public.events e
      WHERE e.id = event_id AND e.user_id = auth.uid()
    )
    OR havkar_private.caller_is_owner()
    OR havkar_private.caller_is_admin()
  );

DROP POLICY IF EXISTS "event seats organizer manage" ON public.event_seats;
CREATE POLICY "event seats organizer manage"
  ON public.event_seats
  FOR ALL
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.events e
      WHERE e.id = event_id AND e.user_id = auth.uid()
    )
    OR havkar_private.caller_is_owner()
    OR havkar_private.caller_is_admin()
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.events e
      WHERE e.id = event_id AND e.user_id = auth.uid()
    )
    OR havkar_private.caller_is_owner()
    OR havkar_private.caller_is_admin()
  );

CREATE OR REPLACE FUNCTION public.havkar_claim_event_seat(
  p_event_id bigint,
  p_seat_label text,
  p_hold_seconds integer DEFAULT 600
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  actor uuid := auth.uid();
  seat public.event_seats%ROWTYPE;
  hold_for integer := GREATEST(60, LEAST(COALESCE(p_hold_seconds, 600), 1800));
BEGIN
  IF actor IS NULL THEN
    RAISE EXCEPTION 'not authenticated' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO seat
  FROM public.event_seats
  WHERE event_id = p_event_id
    AND seat_label = trim(p_seat_label)
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'seat not found' USING ERRCODE = 'P0002';
  END IF;

  IF seat.status = 'sold' OR seat.status = 'blocked' THEN
    RAISE EXCEPTION 'seat unavailable' USING ERRCODE = '22023';
  END IF;

  IF seat.status = 'held'
     AND seat.held_by IS DISTINCT FROM actor
     AND seat.hold_expires_at IS NOT NULL
     AND seat.hold_expires_at > now() THEN
    RAISE EXCEPTION 'seat held by another buyer' USING ERRCODE = '22023';
  END IF;

  UPDATE public.event_seats
  SET status = 'held',
      held_by = actor,
      hold_expires_at = now() + make_interval(secs => hold_for),
      updated_at = now()
  WHERE id = seat.id
  RETURNING * INTO seat;

  RETURN jsonb_build_object(
    'ok', true,
    'seat_id', seat.id,
    'seat_label', seat.seat_label,
    'hold_expires_at', seat.hold_expires_at
  );
END;
$$;

REVOKE ALL ON FUNCTION public.havkar_claim_event_seat(bigint, text, integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.havkar_claim_event_seat(bigint, text, integer) TO authenticated, service_role;

CREATE TABLE IF NOT EXISTS public.event_refund_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id bigint NOT NULL REFERENCES public.event_tickets(id) ON DELETE CASCADE,
  event_id bigint NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
  requester_id uuid NOT NULL REFERENCES auth.users(id),
  reason text,
  status text NOT NULL DEFAULT 'pending',
  reviewer_id uuid,
  review_note text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT event_refund_requests_status_check CHECK (
    status = ANY (ARRAY['pending'::text, 'approved'::text, 'rejected'::text, 'cancelled'::text])
  ),
  CONSTRAINT event_refund_requests_reason_length CHECK (
    reason IS NULL OR char_length(reason) <= 1000
  )
);

CREATE UNIQUE INDEX IF NOT EXISTS event_refund_requests_one_pending_uidx
  ON public.event_refund_requests (ticket_id)
  WHERE status = 'pending';

ALTER TABLE public.event_refund_requests ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "refund requests requester read" ON public.event_refund_requests;
CREATE POLICY "refund requests requester read"
  ON public.event_refund_requests
  FOR SELECT
  TO authenticated
  USING (
    requester_id = auth.uid()
    OR EXISTS (
      SELECT 1 FROM public.events e
      WHERE e.id = event_id AND e.user_id = auth.uid()
    )
    OR havkar_private.caller_is_owner()
    OR havkar_private.caller_is_admin()
  );

DROP POLICY IF EXISTS "refund requests requester insert" ON public.event_refund_requests;
CREATE POLICY "refund requests requester insert"
  ON public.event_refund_requests
  FOR INSERT
  TO authenticated
  WITH CHECK (
    requester_id = auth.uid()
    AND EXISTS (
      SELECT 1 FROM public.event_tickets t
      WHERE t.id = ticket_id
        AND t.user_id = auth.uid()
        AND t.event_id = event_id
    )
  );

COMMENT ON TABLE public.event_seats IS
  'Optional labeled seats for an event. No fake venue floorplan; organizer defines labels.';
COMMENT ON TABLE public.event_refund_requests IS
  'Buyer refund *requests* only. Real Stripe refunds require Owner-approved payment ops; never auto-execute here.';
COMMENT ON COLUMN public.events.venue_lat IS
  'Optional WGS84 latitude. Never invent coordinates when address is unknown.';
COMMENT ON COLUMN public.events.venue_lng IS
  'Optional WGS84 longitude. Never invent coordinates when address is unknown.';
