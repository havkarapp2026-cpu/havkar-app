-- Queue helper: ALWAYS blocked while gates are off. Never invents acceptance.
CREATE OR REPLACE FUNCTION public.havkar_finance_queue_sdi_submission(
  p_document_id bigint,
  p_payload_hash text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  gates public.havkar_finance_issuance_gates%ROWTYPE;
  doc public.havkar_finance_documents%ROWTYPE;
  submission_id bigint;
BEGIN
  IF NOT havkar_private.caller_is_owner() THEN
    RAISE EXCEPTION 'owner_only' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO gates FROM public.havkar_finance_issuance_gates WHERE id = true;
  SELECT * INTO doc FROM public.havkar_finance_documents WHERE id = p_document_id;

  IF doc.id IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'document_not_found');
  END IF;

  IF doc.document_kind <> 'tax_invoice' THEN
    RETURN jsonb_build_object(
      'ok', false,
      'error', 'not_tax_invoice',
      'detail', 'Only tax invoices may be queued for SDI. Payment receipts are never transmitted.'
    );
  END IF;

  IF gates.tax_invoicing_enabled IS NOT TRUE
     OR gates.sdi_enabled IS NOT TRUE
     OR gates.accountant_approved_at IS NULL
     OR coalesce(gates.partita_iva_published, '') = '' THEN
    INSERT INTO public.havkar_finance_sdi_submissions (
      document_id, payload_hash, status, blocked_reason
    ) VALUES (
      p_document_id,
      coalesce(nullif(trim(p_payload_hash), ''), 'blocked'),
      'blocked',
      'SDI disabled until Visura Partita IVA is published and accountant approval is recorded.'
    )
    ON CONFLICT (document_id, payload_hash) DO UPDATE
      SET status = 'blocked',
          blocked_reason = EXCLUDED.blocked_reason,
          updated_at = now()
    RETURNING id INTO submission_id;

    INSERT INTO public.havkar_finance_sdi_audit (submission_id, document_id, actor_user_id, action, detail)
    VALUES (
      submission_id,
      p_document_id,
      auth.uid(),
      'queue_blocked',
      jsonb_build_object(
        'tax_invoicing_enabled', gates.tax_invoicing_enabled,
        'sdi_enabled', gates.sdi_enabled,
        'partita_iva_published', gates.partita_iva_published
      )
    );

    RETURN jsonb_build_object(
      'ok', false,
      'blocked', true,
      'submission_id', submission_id,
      'error', 'sdi_gated_off'
    );
  END IF;

  -- Future path: enqueue only when gates are explicitly armed by Owner+accountant.
  INSERT INTO public.havkar_finance_sdi_submissions (
    document_id, payload_hash, status
  ) VALUES (
    p_document_id, trim(p_payload_hash), 'queued'
  )
  ON CONFLICT (document_id, payload_hash) DO UPDATE
    SET updated_at = now()
  RETURNING id INTO submission_id;

  INSERT INTO public.havkar_finance_sdi_audit (submission_id, document_id, actor_user_id, action, detail)
  VALUES (submission_id, p_document_id, auth.uid(), 'queued', '{}'::jsonb);

  RETURN jsonb_build_object('ok', true, 'submission_id', submission_id, 'status', 'queued');
END;
$$;

REVOKE ALL ON FUNCTION public.havkar_finance_queue_sdi_submission(bigint, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.havkar_finance_queue_sdi_submission(bigint, text) TO authenticated;

