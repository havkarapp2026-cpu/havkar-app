CREATE OR REPLACE FUNCTION public.havkar_mark_messages_delivered(
  p_conversation_id uuid,
  p_message_ids uuid[] DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  uid uuid := auth.uid();
  updated_count integer := 0;
BEGIN
  IF uid IS NULL THEN
    RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '42501';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.conversations c
    WHERE c.id = p_conversation_id
      AND (c.buyer_id = uid OR c.seller_id = uid)
  ) THEN
    RAISE EXCEPTION 'not_conversation_party' USING ERRCODE = '42501';
  END IF;

  UPDATE public.messages m
  SET delivered_at = coalesce(m.delivered_at, now())
  WHERE m.conversation_id = p_conversation_id
    AND m.sender_id <> uid
    AND m.delivered_at IS NULL
    AND (
      p_message_ids IS NULL
      OR m.id = ANY (p_message_ids)
    );

  GET DIAGNOSTICS updated_count = ROW_COUNT;
  RETURN jsonb_build_object('ok', true, 'updated', updated_count, 'status', 'delivered');
END;
$$;

CREATE OR REPLACE FUNCTION public.havkar_mark_messages_read(
  p_conversation_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  uid uuid := auth.uid();
  updated_count integer := 0;
  now_ts timestamptz := now();
BEGIN
  IF uid IS NULL THEN
    RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '42501';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.conversations c
    WHERE c.id = p_conversation_id
      AND (c.buyer_id = uid OR c.seller_id = uid)
  ) THEN
    RAISE EXCEPTION 'not_conversation_party' USING ERRCODE = '42501';
  END IF;

  -- Monotonic: read implies delivered; never clears earlier timestamps.
  UPDATE public.messages m
  SET
    delivered_at = coalesce(m.delivered_at, now_ts),
    read_at = coalesce(m.read_at, now_ts),
    is_read = true
  WHERE m.conversation_id = p_conversation_id
    AND m.sender_id <> uid
    AND (m.read_at IS NULL OR m.is_read IS DISTINCT FROM true);

  GET DIAGNOSTICS updated_count = ROW_COUNT;
  RETURN jsonb_build_object('ok', true, 'updated', updated_count, 'status', 'read');
END;
$$;

REVOKE ALL ON FUNCTION public.havkar_mark_messages_delivered(uuid, uuid[]) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.havkar_mark_messages_read(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.havkar_mark_messages_delivered(uuid, uuid[]) TO authenticated;
GRANT EXECUTE ON FUNCTION public.havkar_mark_messages_read(uuid) TO authenticated;

-- Backfill: previously is_read=true messages get read_at/delivered_at without inventing earlier times.
UPDATE public.messages
SET
  delivered_at = coalesce(delivered_at, created_at),
  read_at = coalesce(read_at, created_at)
WHERE is_read = true
  AND (delivered_at IS NULL OR read_at IS NULL);
