CREATE TABLE IF NOT EXISTS public.havkar_finance_sdi_submissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id bigint NOT NULL REFERENCES public.havkar_finance_documents (id) ON DELETE RESTRICT,
  payload_hash text NOT NULL,
  status text NOT NULL DEFAULT 'draft'
    CHECK (status = ANY (ARRAY[
      'draft','queued','submitted','accepted','rejected','discarded','blocked'
    ])),
  sdi_identifier text,
  rejection_code text,
  rejection_message text,
  attempt_count integer NOT NULL DEFAULT 0,
  last_attempt_at timestamptz,
  blocked_reason text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT havkar_finance_sdi_doc_hash_unique UNIQUE (document_id, payload_hash)
);

CREATE INDEX IF NOT EXISTS havkar_finance_sdi_status_idx
  ON public.havkar_finance_sdi_submissions (status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.havkar_finance_sdi_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id bigint REFERENCES public.havkar_finance_sdi_submissions (id) ON DELETE SET NULL,
  document_id bigint,
  actor_user_id uuid,
  action text NOT NULL,
  detail jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

